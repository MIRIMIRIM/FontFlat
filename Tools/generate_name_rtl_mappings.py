"""Generate finite Apple RTL base tables from tracked original TXT files.

The LR/RL annotation is emitted as separate data; no Unicode directional
controls are inserted here. Runtime direction handling and numeric font
variants remain in the name codec. No network, build hook or OS code page.
"""

from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "FontWeave/Tables/NameEncodings/Apple"
TARGET = ROOT / "FontWeave/Tables/NameRtlData.g.cs"
FILES = {"ARABIC": "Arabic", "FARSI": "Farsi", "HEBREW": "Hebrew"}
ROW = re.compile(r"(0x[0-9A-Fa-f]{2})\s+"
                 r"(?:(<(?:LR|RL)>)\+)?(0x[0-9A-Fa-f]{4,6}(?:\+0x[0-9A-Fa-f]{4,6})*)")


def literal(points):
    return '"' + "".join((f"\\u{point:04X}" if point <= 0xFFFF else f"\\U{point:08X}")
                       for point in points) + '"'


lines = ["// <auto-generated />",
         "// Generated by Tools/generate_name_rtl_mappings.py from the tracked Apple TXT originals.",
         "#nullable enable", "namespace FontWeave.Tables;", "",
         "internal static class NameRtlData", "{"]
for filename, member in FILES.items():
    mapping = {}
    for number, raw in enumerate((SOURCE / (filename + ".TXT")).read_text(encoding="ascii").splitlines(), 1):
        value = raw.split("#", 1)[0].strip()
        if not value:
            continue
        match = ROW.fullmatch(value)
        if match is None:
            raise ValueError(f"{filename}:{number}: unsupported row: {value!r}")
        byte = int(match[1], 16)
        direction = {None: 0, "<LR>": 1, "<RL>": 2}[match[2]]
        points = tuple(int(part[2:], 16) for part in match[3].split("+"))
        if byte in mapping or any(point > 0x10FFFF or 0xD800 <= point <= 0xDFFF for point in points):
            raise ValueError(f"{filename}:{number}: invalid or repeated mapping")
        mapping[byte] = direction, points
    for control in (*range(0x20), 0x7F):
        if control in mapping:
            raise ValueError(f"{filename}: unexpected explicit control")
        mapping[control] = 0, (control,)
    if len(mapping) != 256 or len(set(mapping.values())) != 256:
        raise ValueError(f"{filename}: missing byte or ambiguous tagged reverse mapping")
    lines.extend([f"    internal static readonly string?[] {member} =", "    ["])
    for start in range(0, 256, 8):
        lines.append("        " + ", ".join(literal(mapping[i][1]) for i in range(start, start + 8)) +
                     f", // {start:02X}–{start+7:02X}")
    lines.extend(["    ];", f"    internal static readonly byte[] {member}Directions =", "    ["])
    for start in range(0, 256, 16):
        lines.append("        " + ", ".join(str(mapping[i][0]) for i in range(start, start + 16)) +
                     f", // {start:02X}–{start+15:02X}")
    lines.extend(["    ];", ""])
    print(filename, "256 mapped byte values;",
          sum(direction == 1 for direction, _ in mapping.values()), "LR;",
          sum(direction == 2 for direction, _ in mapping.values()), "RL")
lines.append("}")
TARGET.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(TARGET)
