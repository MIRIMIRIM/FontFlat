"""Generate finite Apple Indic singleton/pair tables from tracked original TXT files.

No ISCII provider, normalization, loose reverse mappings, network or build hook.
Only table-body rows are imported; pair precedence and F0 grammar are implemented
by NameLegacyCodec. The small pair sets stay sparse rather than allocating 64K arrays.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "FontWeave/Tables/NameEncodings/Apple"
TARGET = ROOT / "FontWeave/Tables/NameIndicData.g.cs"
FILES = {"DEVANAGA": "Devanagari", "GUJARATI": "Gujarati", "GURMUKHI": "Gurmukhi"}
ROW = re.compile(r"(0x[0-9A-Fa-f]{2}(?:\+0x[0-9A-Fa-f]{2})?)\s+"
                 r"(0x[0-9A-Fa-f]{4,6}(?:\+0x[0-9A-Fa-f]{4,6})*)")


def literal(points):
    if points is None:
        return "null"
    return '"' + "".join((f"\\u{point:04X}" if point <= 0xFFFF else f"\\U{point:08X}")
                         for point in points) + '"'


lines = ["// <auto-generated />", "// Generated by Tools/generate_name_indic.py from the tracked Apple TXT originals.",
         "#nullable enable", "namespace FontWeave.Tables;", "", "internal static class NameIndicData", "{"]
for filename, member in FILES.items():
    mappings = {}
    for number, raw in enumerate((SOURCE / (filename + ".TXT")).read_text(encoding="ascii").splitlines(), 1):
        value = raw.split("#", 1)[0].strip()
        if not value:
            continue
        match = ROW.fullmatch(value)
        if match is None:
            raise ValueError(f"{filename}:{number}: unsupported row: {value!r}")
        code = int.from_bytes(bytes(int(part, 16) for part in match[1].split("+")), "big")
        points = tuple(int(part[2:], 16) for part in match[2].split("+"))
        if code in mappings or any(point > 0x10FFFF or 0xD800 <= point <= 0xDFFF for point in points):
            raise ValueError(f"{filename}:{number}: invalid or repeated mapping")
        mappings[code] = points
    for control in (*range(0x20), 0x7F):
        if control in mappings:
            raise ValueError(f"{filename}: unexpected explicit control")
        mappings[control] = (control,)
    if len(set(mappings.values())) != len(mappings):
        raise ValueError(f"{filename}: ambiguous reverse mapping")
    pairs = {code: points for code, points in mappings.items() if code > 255}
    if any(code >> 8 == 0xF0 for code in pairs) or 0xF0 in mappings:
        raise ValueError(f"{filename}: F0 extension is specified as unmapped")
    lines.extend([f"    internal static readonly string?[] {member} =", "    ["])
    for start in range(0, 256, 8):
        lines.append("        " + ", ".join(literal(mappings.get(i)) for i in range(start, start + 8)) +
                     f", // {start:02X}–{start+7:02X}")
    lines.extend(["    ];", f"    internal static readonly (ushort Code, string Text)[] {member}Pairs =", "    ["])
    for code, points in sorted(pairs.items()):
        lines.append(f"        (0x{code:04X}, {literal(points)}),")
    lines.extend(["    ];", ""])
    print(filename, len(mappings), "mapped units;", len(pairs), "pairs")
lines.append("}")
TARGET.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(TARGET)
