"""Regenerate the finite Apple SBCS tables. No network, build hook, hash or runtime DSL.

The tracked original TXT files are the authority. Header-only variants are applied in
NameLegacyCodec.cs. Every non-comment row must match the supported one-byte format;
directional or multibyte files cannot accidentally enter this SBCS generator.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "FontWeave/Tables/NameEncodings/Apple"
TARGET = ROOT / "FontWeave/Tables/NameLegacyData.g.cs"
FILES = {
    "ROMAN": "Roman", "CELTIC": "Celtic", "CENTEURO": "CentralEuropean",
    "CROATIAN": "Croatian", "CYRILLIC": "Cyrillic", "DINGBATS": "Dingbats",
    "GAELIC": "Gaelic", "GREEK": "Greek", "ICELAND": "Icelandic", "INUIT": "Inuit",
    "KEYBOARD": "Keyboard", "ROMANIAN": "Romanian", "SYMBOL": "Symbol",
    "THAI": "Thai", "TURKISH": "Turkish",
}
ROW = re.compile(r"0x([0-9A-Fa-f]{2})\s+(0x[0-9A-Fa-f]{4,6}(?:\+0x[0-9A-Fa-f]{4,6})*)")


def literal(points):
    if points is None:
        return "null"
    return '"' + "".join((f"\\u{point:04X}" if point <= 0xFFFF else f"\\U{point:08X}")
                         for point in points) + '"'


lines = ["// <auto-generated />", "// Generated by tools/generate_name_apple.py from the tracked Apple TXT originals.",
         "#nullable enable", "namespace FontWeave.Tables;", "", "internal static class NameLegacyData", "{"]
for filename, member in FILES.items():
    table = [None] * 256
    if filename != "KEYBOARD":
        # Each selected file explicitly specifies these omitted standard controls in its header.
        for byte in (*range(0x20), 0x7F):
            table[byte] = [byte]
    for number, raw in enumerate((SOURCE / (filename + ".TXT")).read_text(encoding="ascii").splitlines(), 1):
        value = raw.split("#", 1)[0].strip()
        if not value:
            continue
        match = ROW.fullmatch(value)
        if match is None:
            raise ValueError(f"{filename}:{number}: not a supported SBCS row: {value!r}")
        byte = int(match[1], 16)
        if table[byte] is not None:
            raise ValueError(f"{filename}:{number}: duplicate byte {byte:02X}")
        points = [int(point[2:], 16) for point in match[2].split("+")]
        if any(point > 0x10FFFF or 0xD800 <= point <= 0xDFFF for point in points):
            raise ValueError(f"{filename}:{number}: invalid Unicode scalar")
        table[byte] = points
    if filename == "TURKISH":
        # Header explicitly calls F5 undefined; F8A0 is only an artificial roundtrip placeholder.
        assert table[0xF5] == [0xF8A0]
        table[0xF5] = None
    lines.extend([f"    internal static readonly string?[] {member} =", "    ["])
    for start in range(0, 256, 8):
        lines.append("        " + ", ".join(literal(table[i]) for i in range(start, start + 8)) +
                     f", // {start:02X}–{start+7:02X}")
    lines.extend(["    ];", ""])
lines.append("}")
TARGET.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(TARGET)
