    {
        // Internal so the sanctioned source-closure validation mode can observe the
        // bound view's location; spec section 0 keeps mechanical helpers internal.
        writer.Line("internal global::FontWeave.Core.DataLocation Location => NormalizeLocation(_location);");
        writer.Line();
        writer.Line("private static global::FontWeave.Core.DataLocation NormalizeLocation(global::FontWeave.Core.DataLocation location) =>");
        writer.Indent++;
        writer.Line($"location == default ? global::FontWeave.Core.DataLocation.Anonymous(0x{model.Tag:X8}u) : location;");
        writer.Indent--;
        writer.Line();
        writer.Line("private static bool TrySlice(global::System.ReadOnlySpan<byte> bytes, ulong offset, ulong length,");
        writer.Indent++;
        writer.Line("out global::System.ReadOnlySpan<byte> value)");
        writer.Indent--;
        writer.Line("{");
        writer.Indent++;
        writer.Line("value = default;");
        writer.Line("if (offset > (ulong)bytes.Length || length > (ulong)bytes.Length - offset) return false;");
        writer.Line("value = bytes.Slice((int)offset, (int)length);");
        writer.Line("return true;");
        writer.Indent--;
        writer.Line("}");
