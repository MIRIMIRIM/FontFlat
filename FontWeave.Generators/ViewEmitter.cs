        if (baseScalar is not null)
        {
            writer.Line($"status = TryGet{payload.Base}(out var baseRaw, out diagnostic);");
            writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
            writer.Line("ulong storageBase = (ulong)baseRaw;");
            writer.Line($"status = TryEvaluateScalar{baseScalar.Name}Position(out ulong basePosition, out diagnostic);");
            writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
            if (!baseScalar.ZeroAllowed)
            {
                writer.Line("if (storageBase == 0)");
                writer.Indent++;
                writer.Line("return Fail(global::FontWeave.Core.ReadStatus.InvalidOffset,");
                writer.Indent++;
                writer.Line("global::FontWeave.Core.DiagnosticCode.InvalidValue,");
                writer.Line($"Location.AtLocal((global::FontWeave.Core.DataField){baseScalar.FieldId}, basePosition),");
                writer.Line("out diagnostic, 0, 1);");
                writer.Indent -= 2;
            }
            writer.Line("if (storageBase < minimum)");
            writer.Indent++;
            writer.Line("return Fail(global::FontWeave.Core.ReadStatus.InvalidOffset,");
            writer.Indent++;
            writer.Line("global::FontWeave.Core.DiagnosticCode.StorageBeforeRecords,");
            writer.Line($"Location.AtLocal((global::FontWeave.Core.DataField){baseScalar.FieldId}, basePosition), out diagnostic,");
            writer.Line("storageBase, minimum);");
            writer.Indent -= 2;
            writer.Line("if (storageBase > (ulong)_data.Length)");
            writer.Indent++;
            writer.Line("return Fail(global::FontWeave.Core.ReadStatus.InvalidOffset,");
            writer.Indent++;
            writer.Line("global::FontWeave.Core.DiagnosticCode.RangeOutsideSource,");
            writer.Line($"Location.AtLocal((global::FontWeave.Core.DataField){baseScalar.FieldId}, basePosition), out diagnostic,");
            writer.Line("storageBase, (ulong)_data.Length);");
            writer.Indent -= 2;
        }
        writer.Line($"ulong encodedOffset = (ulong)record.{payload.Offset};");

        if (!offset.ZeroAllowed)
        {
            writer.Line("if (encodedOffset == 0)");
            writer.Line("{");
            writer.Indent++;
            writer.Line($"status = TryEvaluateArray{array.Name}Start(out ulong arrayStart, out diagnostic);");
            writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
            writer.Line($"ulong fieldPosition = arrayStart + (ulong)ordinal * {U(array.Stride)} + {U(offset.Position.Constant)};");
            writer.Line("return Fail(global::FontWeave.Core.ReadStatus.InvalidOffset,");
            writer.Indent++;
            writer.Line("global::FontWeave.Core.DiagnosticCode.InvalidValue,");
            writer.Line($"Location.AtLocal((global::FontWeave.Core.DataField){offset.FieldId}, fieldPosition, ordinal),");
            writer.Line("out diagnostic, 0, 1);");
            writer.Indent -= 2;
            writer.Line("}");
        }

        writer.Line($"ulong absoluteOffset = {(baseScalar is null ? "" : "storageBase + ")}encodedOffset * {U(offset.Scale)};");
        if (baseScalar is null)
        {
            writer.Line("if (absoluteOffset < minimum)");
            writer.Line("{");
            writer.Indent++;
            writer.Line($"status = TryEvaluateArray{array.Name}Start(out ulong arrayStart, out diagnostic);");
            writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
            writer.Line($"ulong fieldPosition = arrayStart + (ulong)ordinal * {U(array.Stride)} + {U(offset.Position.Constant)};");
            writer.Line("return Fail(global::FontWeave.Core.ReadStatus.InvalidOffset,");
            writer.Indent++;
            writer.Line("global::FontWeave.Core.DiagnosticCode.StorageBeforeRecords,");
            writer.Line($"Location.AtLocal((global::FontWeave.Core.DataField){offset.FieldId}, fieldPosition, ordinal),");
            writer.Line("out diagnostic, absoluteOffset, minimum);");
            writer.Indent -= 2;
            writer.Line("}");
        }
        writer.Line($"ulong payloadLength = (ulong)record.{payload.Length};");
        writer.Line("if (!TrySlice(_data, absoluteOffset, payloadLength, out payload))");
        writer.Indent++;
        writer.Line("return Fail(global::FontWeave.Core.ReadStatus.InvalidOffset,");
        writer.Indent++;
        writer.Line("global::FontWeave.Core.DiagnosticCode.RangeOutsideSource,");
        writer.Line("Location.AtLocal(global::FontWeave.Core.DataField.Payload, absoluteOffset, ordinal),");
        writer.Line("out diagnostic, absoluteOffset + payloadLength, (ulong)_data.Length);");
        writer.Indent -= 2;
        writer.Line("diagnostic = default;");
        writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
        writer.Indent--;
        writer.Line("}");
    }

    // Spec 3 typed reference opener family (card 1.2-b/c): fixed check order — unbound,
    // known version, applicability (A3 references carry no condition and always apply),
    // ordinal/count (counted-array form, A1 semantics), the offset field through its own
    // accessor (truncation propagates), zero policy, base/minimum/length with wide
    // arithmetic, source bounds, and finally the child TryOpen with the child location
    // translated exactly once via Location.AtLocal. Any failure restores every out value.
    private static void EmitReferenceOpener(CodeWriter writer, TableModel model, ReferenceModel reference)
    {
        ArrayModel? array = reference.ArrayName is null ? null : FindArray(model, reference.ArrayName);
        bool externForm = array is { ExternallyPositioned: true };
        ScalarModel offset = array is null ? FindScalar(model, reference.OffsetField) : FindArrayField(array, reference.OffsetField);
        string targetView = reference.TargetNamespace.Length == 0
            ? reference.TargetName
            : "global::" + reference.TargetNamespace + "." + reference.TargetName;
        string refField = $"(global::FontWeave.Core.DataField){offset.FieldId}";
        string declare = "global::FontWeave.Core.ReadStatus status";
        string ordinalArgument = array is null ? "-1" : "ordinal";
        // Spec 3.3/6.1: a table that declares a RoleType opens its typed references through
        // a concrete RoleEnum parameter leading the value parameters ahead of the out
        // values; views without a RoleType keep the A1-A3 signatures byte for byte.
        bool roleDispatch = model.RoleType is not null;
        string roleType = "global::" + model.RoleType;
        string roleParameter = roleDispatch ? roleType + " role, " : "";

        if (externForm)
        {
            writer.Line($"internal global::FontWeave.Core.ReadStatus TryOpen{reference.Name}At({roleParameter}ulong rowPosition, int ordinal,");
            writer.Indent++;
            writer.Line($"out {targetView} child, out bool present, out global::FontWeave.Core.FontDiagnostic diagnostic)");
            writer.Indent--;
        }
        else if (array is not null)
        {
            writer.Line($"internal global::FontWeave.Core.ReadStatus TryOpen{reference.Name}({roleParameter}int ordinal, out {targetView} child, out bool present,");
            writer.Indent++;
            writer.Line("out global::FontWeave.Core.FontDiagnostic diagnostic)");
            writer.Indent--;
        }
        else
        {
            writer.Line($"internal global::FontWeave.Core.ReadStatus TryOpen{reference.Name}({roleParameter}out {targetView} child, out bool present,");
            writer.Indent++;
            writer.Line("out global::FontWeave.Core.FontDiagnostic diagnostic)");
            writer.Indent--;
        }
        writer.Line("{");
        writer.Indent++;
        writer.Line("child = default;");
        writer.Line("present = false;");
        // Every generated accessor family reports the unbound contract at the owner
        // start (A1/A2 convention); the scalar opener form matches the array form
        // minus the ordinal so consumers can predict unbound locations uniformly.
        string unboundLocation = externForm
            ? "Location.AtLocal(global::FontWeave.Core.DataField.None, rowPosition, ordinal)"
            : "Location.AtLocal(global::FontWeave.Core.DataField.None, 0UL" + (array is null ? "" : ", ordinal") + ")";
        writer.Line("if (!IsBound)");
        writer.Indent++;
        writer.Line("return Fail(global::FontWeave.Core.ReadStatus.Uninitialized,");
        writer.Indent++;
        writer.Line("global::FontWeave.Core.DiagnosticCode.UnboundView,");
        writer.Line(unboundLocation + ", out diagnostic);");
        writer.Indent -= 2;

        // Spec 3.4 check order: role validity first, then the known version, then the
        // applicability conditions. An unknown role refuses at the owner start with the
        // unchecked sign-extended value as its Detail (card 1.2-b, spec 4).
        if (roleDispatch)
        {
            writer.Line("switch (role)");
            writer.Line("{");
            writer.Indent++;
            foreach (var supported in model.SupportedRoles)
                writer.Line($"case {roleType}.{MemberName(model, supported)}:");
            writer.Indent++;
            writer.Line("break;");
            writer.Indent--;
            writer.Line("default:");
            writer.Indent++;
            writer.Line("return Fail(global::FontWeave.Core.ReadStatus.UnsupportedFormat,");
            writer.Indent++;
            writer.Line("global::FontWeave.Core.DiagnosticCode.UnsupportedOperation,");
            writer.Line("Location.AtLocal(global::FontWeave.Core.DataField.None, 0UL), out diagnostic,");
            writer.Line("unchecked((ulong)(long)role), 0UL);");
            writer.Indent -= 3;
            writer.Line("}");
        }

        writer.Line($"{declare} = TryRequireKnownVersion(out _, out diagnostic);");
        writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");

        if (reference.WhenRoles.Length != 0)
        {
            // An inapplicable role refuses exactly like an unknown one (card 1.2-b): same
            // status/code at the owner start, Detail=role, Expected=0.
            var inapplicable = new StringBuilder();
            for (int i = 0; i < reference.WhenRoles.Length; i++)
            {
                if (i != 0) inapplicable.Append(" && ");
                inapplicable.Append("role != ").Append(roleType).Append('.').Append(MemberName(model, reference.WhenRoles[i]));
            }
            writer.Line($"if ({inapplicable})");
            writer.Line("{");
            writer.Indent++;
            writer.Line("return Fail(global::FontWeave.Core.ReadStatus.UnsupportedFormat,");
            writer.Indent++;
            writer.Line("global::FontWeave.Core.DiagnosticCode.UnsupportedOperation,");
            writer.Line("Location.AtLocal(global::FontWeave.Core.DataField.None, 0UL), out diagnostic,");
            writer.Line("unchecked((ulong)(long)role), 0UL);");
            writer.Indent -= 2;
            writer.Line("}");
        }
        if (reference.Selector is { } selectorName && reference.SelectorValues.Length != 0)
        {
            // The selector is re-read through its own accessor ahead of the ordinal and
            // offset fields (no billing); an unmatched value refuses at the selector field
            // with Detail=value and Expected=0 (spec 4).
            ScalarModel selector = FindScalar(model, selectorName);
            writer.Line($"status = TryGet{selectorName}(out {selector.CsType} selectorValue, out diagnostic);");
            writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
            var unmatched = new StringBuilder();
            for (int i = 0; i < reference.SelectorValues.Length; i++)
            {
                if (i != 0) unmatched.Append(" && ");
                unmatched.Append("selectorValue != ").Append(reference.SelectorValues[i]).Append('U');
            }
            writer.Line($"if ({unmatched})");
            writer.Line("{");
            writer.Indent++;
            writer.Line("return Fail(global::FontWeave.Core.ReadStatus.UnsupportedFormat,");
            writer.Indent++;
            writer.Line("global::FontWeave.Core.DiagnosticCode.UnsupportedOperation,");
            writer.Line($"Location.AtLocal((global::FontWeave.Core.DataField){selector.FieldId}, {U(selector.Position.Constant)}), out diagnostic,");
            writer.Line("selectorValue, 0UL);");
            writer.Indent -= 2;
            writer.Line("}");
        }

        string offsetValue;
        string fieldPosition;
        if (externForm)
        {
            // An externally positioned record declares no count, so there is no ordinal
            // gate; the record reader reports row truncation with the passed ordinal.
            writer.Line($"status = TryRead{array!.Name}At(rowPosition, ordinal, out var record, out diagnostic);");
            writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
            offsetValue = $"(ulong)record.{offset.Name}";
            fieldPosition = $"rowPosition > ulong.MaxValue - {U(offset.Position.Constant)} ? ulong.MaxValue : rowPosition + {U(offset.Position.Constant)}";
        }
        else if (array is not null)
        {
            writer.Line($"status = TryGet{array.Count}(out var countRaw, out diagnostic);");
            writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
            writer.Line("ulong count = (ulong)countRaw;");
            writer.Line("if (ordinal < 0 || (ulong)ordinal >= count)");
            writer.Line("{");
            writer.Indent++;
            string countLocation = EmitCountLocation(writer, model, array, "ordinal");
            writer.Line("return Fail(global::FontWeave.Core.ReadStatus.InvalidIndex,");
            writer.Indent++;
            writer.Line("global::FontWeave.Core.DiagnosticCode.IndexOutOfRange,");
            writer.Line(countLocation + ",");
            writer.Line("out diagnostic, unchecked((ulong)ordinal), count);");
            writer.Indent -= 2;
            writer.Line("}");
            writer.Line($"status = TryGet{array.Name}(ordinal, out var record, out diagnostic);");
            writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
            writer.Line($"status = TryEvaluateArray{array.Name}Start(out ulong arrayStart, out diagnostic);");
            writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
            offsetValue = $"(ulong)record.{offset.Name}";
            fieldPosition = $"arrayStart + (ulong)ordinal * {U(array.Stride)} + {U(offset.Position.Constant)}";
        }
        else
        {
            writer.Line($"status = TryGet{offset.Name}(out {offset.CsType} raw, out diagnostic);");
            writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
            offsetValue = "(ulong)raw";
            fieldPosition = U(offset.Position.Constant);
        }
        string refLocation = $"Location.AtLocal({refField}, {fieldPosition}, {ordinalArgument})";

        if (reference.NullPolicy != ReferenceNullPolicy.ZeroIsAddress)
        {
            writer.Line($"if ({offsetValue} == 0UL)");
            writer.Line("{");
            writer.Indent++;
            if (reference.NullPolicy == ReferenceNullPolicy.Optional)
            {
                // Spec 3.4: a nullable absence neither opens the child nor evaluates the
                // declared Minimum/Length values.
                writer.Line("diagnostic = default;");
                writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
            }
            else if (reference.ZeroFailure == ReferenceZeroFailure.InvalidValue)
            {
                writer.Line("return Fail(global::FontWeave.Core.ReadStatus.InvalidFormat,");
                writer.Indent++;
                writer.Line("global::FontWeave.Core.DiagnosticCode.InvalidValue,");
                writer.Line($"{refLocation}, out diagnostic, 0UL, 1UL);");
                writer.Indent--;
            }
            else
            {
                writer.Line("return Fail(global::FontWeave.Core.ReadStatus.InvalidOffset,");
                writer.Indent++;
                writer.Line("global::FontWeave.Core.DiagnosticCode.RangeOutsideSource,");
                writer.Line($"{refLocation}, out diagnostic, 0UL, (ulong)_data.Length);");
                writer.Indent--;
            }
            writer.Indent--;
            writer.Line("}");
        }

        string baseValue;
        if (reference.Origin == ReferenceOrigin.NamedBase)
        {
            writer.Line($"status = TryGet{reference.Base}(out var baseRaw, out diagnostic);");
            writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
            baseValue = "(ulong)baseRaw";
        }
        else if (reference.Origin == ReferenceOrigin.RecordStart && array is { ExternallyPositioned: false })
        {
            writer.Line($"ulong rowPosition = arrayStart + (ulong)ordinal * {U(array.Stride)};");
            baseValue = "rowPosition";
        }
        else if (reference.Origin == ReferenceOrigin.RecordStart)
        {
            baseValue = "rowPosition";
        }
        else
            baseValue = "0UL";
        if (baseValue != "0UL" || offset.Scale != 1)
        {
            // Spec 3.4: base+offset*Scale overflow refuses with wide arithmetic before any
            // narrow conversion; the guard is unreachable for schemas whose worst case was
            // proven at build time but stays defensive at runtime.
            writer.Line($"if ({offsetValue} > (ulong.MaxValue - {baseValue}) / {U(offset.Scale)})");
            writer.Line("{");
            writer.Indent++;
            writer.Line("return Fail(global::FontWeave.Core.ReadStatus.InvalidOffset,");
            writer.Indent++;
            writer.Line("global::FontWeave.Core.DiagnosticCode.RangeOutsideSource,");
            writer.Line($"{refLocation},");
            writer.Line($"out diagnostic, {offsetValue}, (ulong.MaxValue - {baseValue}) / {U(offset.Scale)});");
            writer.Indent -= 2;
            writer.Line("}");
        }
        writer.Line($"ulong target = {baseValue} + {offsetValue} * {U(offset.Scale)};");

        if (reference.Minimum is { } minimumName)
        {
            writer.Line($"status = TryGet{minimumName}(out var minimumRaw, out diagnostic);");
            writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
            writer.Line("ulong minimum = (ulong)minimumRaw;");
            writer.Line("if (target < minimum)");
            writer.Line("{");
            writer.Indent++;
            writer.Line("return Fail(global::FontWeave.Core.ReadStatus.InvalidOffset,");
            writer.Indent++;
            writer.Line("global::FontWeave.Core.DiagnosticCode.StorageBeforeRecords,");
            writer.Line($"{refLocation}, out diagnostic, target, minimum);");
            writer.Indent -= 2;
            writer.Line("}");
        }

        string window;
        if (reference.Length is { } lengthName)
        {
            string lengthField;
            if (array is not null)
            {
                writer.Line($"ulong windowLength = (ulong)record.{lengthName};");
                ScalarModel lengthElement = FindArrayField(array, lengthName);
                lengthField = $"(global::FontWeave.Core.DataField){lengthElement.FieldId}";
            }
            else
            {
                writer.Line($"status = TryGet{lengthName}(out var lengthRaw, out diagnostic);");
                writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
                writer.Line("ulong windowLength = (ulong)lengthRaw;");
                ScalarModel lengthScalar = FindScalar(model, lengthName);
                lengthField = $"(global::FontWeave.Core.DataField){lengthScalar.FieldId}";
            }
            string lengthLocation = array is null
                ? $"Location.AtLocal({lengthField}, {U(FindScalar(model, lengthName).Position.Constant)})"
                : $"Location.AtLocal({lengthField}, {fieldPosition} - {U(offset.Position.Constant)} + {U(FindArrayField(array, lengthName).Position.Constant)}, {ordinalArgument})";
            writer.Line("if (windowLength > (ulong)_data.Length - target)");
            writer.Line("{");
            writer.Indent++;
            writer.Line("return Fail(global::FontWeave.Core.ReadStatus.InvalidOffset,");
            writer.Indent++;
            writer.Line("global::FontWeave.Core.DiagnosticCode.RangeOutsideSource,");
            writer.Line($"{lengthLocation}, out diagnostic, windowLength, (ulong)_data.Length - target);");
            writer.Indent -= 2;
            writer.Line("}");
            window = "_data.Slice((int)target, (int)windowLength)";
        }
        else
            window = "_data.Slice((int)target)";

        writer.Line($"if (target {(reference.AllowTargetAtEnd ? ">" : ">=")} (ulong)_data.Length)");
        writer.Line("{");
        writer.Indent++;
        writer.Line("return Fail(global::FontWeave.Core.ReadStatus.InvalidOffset,");
        writer.Indent++;
        writer.Line("global::FontWeave.Core.DiagnosticCode.RangeOutsideSource,");
        writer.Line($"{refLocation}, out diagnostic, target, (ulong)_data.Length);");
        writer.Indent -= 2;
        writer.Line("}");

        writer.Line($"status = {targetView}.TryOpen({window}, out child, out diagnostic,");
        writer.Indent++;
        // The child location is translated exactly once (spec 3.2); the target TryOpen
        // failure propagates verbatim with child/present restored.
        writer.Line("Location.AtLocal(global::FontWeave.Core.DataField.None, target));");
        writer.Indent--;
        writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
        writer.Line("present = true;");
        writer.Line("diagnostic = default;");
        writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
        writer.Indent--;
        writer.Line("}");
    }

    // Spec 7.2 plan-time fixup helper (card 1.2-d): the planner has already chosen the
    // branch and target; the helper only validates and encodes. fieldLocation arrives
    // qualified and is never shifted again. Every failure leaves encoded at 0.
    private static void EmitReferenceFixup(CodeWriter writer, TableModel model, ReferenceModel reference)
    {
        ScalarModel offset = reference.ArrayName is null
            ? FindScalar(model, reference.OffsetField)
            : FindArrayField(FindArray(model, reference.ArrayName), reference.OffsetField);
        writer.Line($"internal static global::FontWeave.Core.ReadStatus TryGet{reference.Name}OffsetValue(bool present, ulong origin, ulong target,");
        writer.Indent++;
        writer.Line($"out {offset.CsType} encoded, out global::FontWeave.Core.FontDiagnostic diagnostic,");
        writer.Line("global::FontWeave.Core.DataLocation fieldLocation = default)");
        writer.Indent--;
        writer.Line("{");
        writer.Indent++;
        writer.Line("encoded = default;");
        writer.Line("fieldLocation = NormalizeLocation(fieldLocation);");
        writer.Line("if (!present)");
        writer.Line("{");
        writer.Indent++;
        if (reference.NullPolicy == ReferenceNullPolicy.Optional)
        {
            writer.Line("diagnostic = default;");
            writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
        }
        else
        {
            writer.Line("return Fail(global::FontWeave.Core.ReadStatus.InvalidFormat,");
            writer.Indent++;
            writer.Line("global::FontWeave.Core.DiagnosticCode.InvalidValue,");
            writer.Line("fieldLocation, out diagnostic, 0UL, 1UL);");
            writer.Indent--;
        }
        writer.Indent--;
        writer.Line("}");
        writer.Line("if (target < origin)");
        writer.Line("{");
        writer.Indent++;
        writer.Line("return Fail(global::FontWeave.Core.ReadStatus.UnsupportedFormat,");
        writer.Indent++;
        writer.Line("global::FontWeave.Core.DiagnosticCode.UnsupportedOperation,");
        writer.Line("fieldLocation, out diagnostic, target, origin);");
        writer.Indent -= 2;
        writer.Line("}");
        writer.Line("ulong delta = target - origin;");
        writer.Line($"if (delta % {U(offset.Scale)} != 0UL)");
        writer.Line("{");
        writer.Indent++;
        writer.Line("return Fail(global::FontWeave.Core.ReadStatus.UnsupportedFormat,");
        writer.Indent++;
        writer.Line("global::FontWeave.Core.DiagnosticCode.UnsupportedOperation,");
        writer.Line($"fieldLocation, out diagnostic, delta, {U(offset.Scale)});");
        writer.Indent -= 2;
        writer.Line("}");
        writer.Line($"ulong wide = delta / {U(offset.Scale)};");
        writer.Line($"if (wide > {U(RawBound(offset))})");
        writer.Line("{");
        writer.Indent++;
        writer.Line("return Fail(global::FontWeave.Core.ReadStatus.UnsupportedFormat,");
        writer.Indent++;
        writer.Line("global::FontWeave.Core.DiagnosticCode.UnsupportedOperation,");
        writer.Line($"fieldLocation, out diagnostic, wide, {U(RawBound(offset))});");
        writer.Indent -= 2;
        writer.Line("}");
        if (reference.NullPolicy != ReferenceNullPolicy.ZeroIsAddress)
        {
            writer.Line("if (wide == 0UL)");
            writer.Line("{");
            writer.Indent++;
            writer.Line("return Fail(global::FontWeave.Core.ReadStatus.UnsupportedFormat,");
            writer.Indent++;
            writer.Line("global::FontWeave.Core.DiagnosticCode.UnsupportedOperation,");
            writer.Line("fieldLocation, out diagnostic, 0UL, 1UL);");
            writer.Indent -= 2;
            writer.Line("}");
        }
        writer.Line($"encoded = ({offset.CsType})wide;");
        writer.Line("diagnostic = default;");
        writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
        writer.Indent--;
        writer.Line("}");
    }

    private static ulong RawBound(ScalarModel value) => value.Type switch
    {
        WireType.UInt8 => byte.MaxValue, WireType.Int8 => (ulong)sbyte.MaxValue,
        WireType.UInt16 => ushort.MaxValue, WireType.UInt24 => 0xFFFFFF,
        WireType.UInt32 => uint.MaxValue, WireType.Int16 => (ulong)short.MaxValue,
        WireType.Int64 => long.MaxValue, _ => int.MaxValue
    };

    private static void EmitKnownVersion(CodeWriter writer, TableModel model)
    {
        writer.Line("private global::FontWeave.Core.ReadStatus TryRequireKnownVersion(out ulong version,");
        writer.Indent++;
        writer.Line("out global::FontWeave.Core.FontDiagnostic diagnostic)");
        writer.Indent--;
        writer.Line("{");
        writer.Indent++;
        writer.Line("version = default;");
        if (model.VersionField is null)
        {
            writer.Line("diagnostic = default;");
            writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
        }
        else
        {
            ScalarModel version = FindScalar(model, model.VersionField);
            writer.Line($"global::FontWeave.Core.ReadStatus status = TryGet{version.Name}(out {version.CsType} rawVersion, out diagnostic);");
            writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
            writer.Line("version = (ulong)rawVersion;");
            if (model.SupportedVersions.Length != 0)
            {
                var condition = new StringBuilder();
                for (int i = 0; i < model.SupportedVersions.Length; i++)
                {
                    if (i != 0) condition.Append(" || ");
                    condition.Append("version == ").Append(U(model.SupportedVersions[i]));
                }
                writer.Line($"if ({condition})");
                writer.Line("{");
                writer.Indent++;
                writer.Line("diagnostic = default;");
                writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
                writer.Indent--;
                writer.Line("}");
            }
            writer.Line($"status = TryEvaluateScalar{version.Name}Position(out ulong versionPosition, out diagnostic);");
            writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
            writer.Line("return Fail(global::FontWeave.Core.ReadStatus.UnsupportedFormat,");
            writer.Indent++;
            writer.Line("global::FontWeave.Core.DiagnosticCode.UnsupportedVersion,");
            writer.Line($"Location.AtLocal((global::FontWeave.Core.DataField){version.FieldId}, versionPosition),");
            writer.Line("out diagnostic, version);");
            writer.Indent--;
        }
        writer.Indent--;
        writer.Line("}");
    }

    private static void EmitRuntimeHelpers(CodeWriter writer, TableModel model)
    {
        // Internal so the sanctioned source-closure validation mode can observe the
        // bound view's location; spec section 0 keeps mechanical helpers internal.
        writer.Line("internal global::FontWeave.Core.DataLocation Location => NormalizeLocation(_location);");
        writer.Line();
        writer.Line("private static global::FontWeave.Core.DataLocation NormalizeLocation(global::FontWeave.Core.DataLocation location) =>");
        writer.Indent++;
        writer.Line($"location == default ? global::FontWeave.Core.DataLocation.Anonymous(0x{model.Tag:X8}u) : location;");
        writer.Indent--;
        writer.Line();
        writer.Line("private static bool TrySlice(global::System.ReadOnlySpan<byte> bytes, ulong offset, ulong length,");
        writer.Indent++;
        writer.Line("out global::System.ReadOnlySpan<byte> value)");
        writer.Indent--;
        writer.Line("{");
        writer.Indent++;
        writer.Line("value = default;");
        writer.Line("if (offset > (ulong)bytes.Length || length > (ulong)bytes.Length - offset) return false;");
        writer.Line("value = bytes.Slice((int)offset, (int)length);");
        writer.Line("return true;");
        writer.Indent--;
        writer.Line("}");
        writer.Line();
        writer.Line("private static global::FontWeave.Core.ReadStatus Fail(global::FontWeave.Core.ReadStatus status,");
        writer.Indent++;
        writer.Line("global::FontWeave.Core.DiagnosticCode code, global::FontWeave.Core.DataLocation location,");
        writer.Line("out global::FontWeave.Core.FontDiagnostic diagnostic, ulong detail = 0, ulong expected = 0)");
        writer.Indent--;
        writer.Line("{");
        writer.Indent++;
        writer.Line("diagnostic = new global::FontWeave.Core.FontDiagnostic(code, location, detail, expected);");
        writer.Line("return status;");
        writer.Indent--;
        writer.Line("}");
    }

    private static void EmitPosition(CodeWriter writer, PositionModel position, string target,
        uint subtract = 0, int countFieldId = 0)
    {
        writer.Line($"{target} = default;");
        writer.Line($"ulong computedPosition = {U(position.Constant)};");
        if (position.Base is not null)
        {
            writer.Line($"global::FontWeave.Core.ReadStatus baseStatus = TryGet{position.Base}(out var baseValue, out diagnostic);");
            writer.Line("if (baseStatus != global::FontWeave.Core.ReadStatus.Done) return baseStatus;");
            writer.Line("computedPosition += (ulong)baseValue;");
        }
        if (position.Count is not null)
        {
            writer.Line($"global::FontWeave.Core.ReadStatus countStatus = TryGet{position.Count}(out var countValue, out diagnostic);");
            writer.Line("if (countStatus != global::FontWeave.Core.ReadStatus.Done) return countStatus;");
            if (subtract != 0)
            {
                // Affine subtraction happens before the stride multiplication (spec 2.2);
                // a runtime underflow is refused at the raw count source and never wraps.
                writer.Line($"if ((ulong)countValue < {U(subtract)})");
                writer.Line("{");
                writer.Indent++;
                writer.Line($"global::FontWeave.Core.ReadStatus underflowStatus = TryEvaluateScalar{position.Count}Position(out ulong countPosition, out diagnostic);");
                writer.Line("if (underflowStatus != global::FontWeave.Core.ReadStatus.Done) return underflowStatus;");
                writer.Line("return Fail(global::FontWeave.Core.ReadStatus.InvalidFormat,");
                writer.Indent++;
                writer.Line("global::FontWeave.Core.DiagnosticCode.InvalidValue,");
                writer.Line($"Location.AtLocal((global::FontWeave.Core.DataField){countFieldId}, countPosition),");
                writer.Line($"out diagnostic, (ulong)countValue, {U(subtract)});");
                writer.Indent -= 2;
                writer.Line("}");
                writer.Line($"computedPosition += ((ulong)countValue - {U(subtract)}) * {U(position.Stride)};");
            }
            else
                writer.Line($"computedPosition += (ulong)countValue * {U(position.Stride)};");
        }
        writer.Line($"{target} = computedPosition;");
    }

    private static string ReadExpression(ScalarModel scalar, string bytes, ulong offset)
    {
        if (scalar.Type == WireType.UInt24)
        {
            ulong high = scalar.Endian == WireEndian.Big ? offset : offset + 2;
            ulong low = scalar.Endian == WireEndian.Big ? offset + 2 : offset;
            return $"((uint){bytes}[{high}] << 16) | ((uint){bytes}[{offset + 1}] << 8) | {bytes}[{low}]";
        }
        if (scalar.Type is WireType.UInt8 or WireType.Int8)
        {
            string value = $"{bytes}[{offset.ToString(CultureInfo.InvariantCulture)}]";
            return scalar.Type == WireType.Int8 ? $"unchecked((sbyte){value})" : value;
        }
        string suffix = scalar.Endian == WireEndian.Big ? "BigEndian" : "LittleEndian";
        string method = scalar.Type switch
        {
            WireType.UInt16 => "ReadUInt16",
            WireType.UInt32 => "ReadUInt32",
            WireType.Int16 => "ReadInt16",
            WireType.Int64 => "ReadInt64",
            _ => "ReadInt32",
        };
        string source = offset == 0 ? bytes : $"{bytes}.Slice({offset.ToString(CultureInfo.InvariantCulture)})";
        return $"global::System.Buffers.Binary.BinaryPrimitives.{method}{suffix}({source})";
    }

    private static ScalarModel FindScalar(TableModel model, string name)
    {
        foreach (ScalarModel scalar in model.Scalars)
            if (scalar.Name == name) return scalar;
        throw new InvalidOperationException($"Scalar '{name}' was not found in '{model.Name}'.");
    }

    // The declared member name of a supported role value; the parser only accepts values
    // the RoleType declares, so the lookup cannot fail for an emitting model.
    private static string MemberName(TableModel model, long value)
    {
        foreach (RoleMemberModel member in model.RoleMembers)
            if (member.Value == value) return member.Name;
        throw new InvalidOperationException($"Role value {value} has no declared member in '{model.Name}'.");
    }

    private static ScalarModel? FindScalarOrNull(TableModel model, string name)
    {
        foreach (ScalarModel scalar in model.Scalars)
            if (scalar.Name == name) return scalar;
        return null;
    }

    private static ComputedModel? FindComputed(TableModel model, string name)
    {
        foreach (ComputedModel computed in model.Computed)
            if (computed.Name == name) return computed;
        return null;
    }

    // Emits the statements evaluating the declared diagnostic provenance of the array's
    // count source and returns the AtLocal expression (with the optional ordinal, when
    // the caller reports one). Scalar counts keep their own position and field; derived
    // counts locate the unique raw scalar source; computed counts use the declared
    // DiagnosticSource position with the computed's DiagnosticField (card 1.2-c/e).
    private static string EmitCountLocation(CodeWriter writer, TableModel model, ArrayModel array, string? ordinal)
    {
        string tail = ordinal is null ? ")" : $", {ordinal})";
        if (FindScalarOrNull(model, array.Count) is { } scalar)
        {
            writer.Line($"status = TryEvaluateScalar{scalar.Name}Position(out ulong countPosition, out diagnostic);");
            writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
            return $"Location.AtLocal((global::FontWeave.Core.DataField){scalar.FieldId}, countPosition{tail}";
        }
        if (FindComputed(model, array.Count) is { } computed)
        {
            if (computed.DiagnosticSource is { } source)
            {
                writer.Line($"status = TryEvaluateScalar{source}Position(out ulong countPosition, out diagnostic);");
                writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
                return $"Location.AtLocal((global::FontWeave.Core.DataField){computed.DiagnosticFieldId}, countPosition{tail}";
            }
            return $"Location.AtLocal((global::FontWeave.Core.DataField){computed.DiagnosticFieldId}, 0{tail}";
        }
        var derived = model.Derived.First(d => d.Name == array.Count);
        if (FindScalarOrNull(model, derived.Expression.Count ?? "") is not { } raw)
            return $"Location.AtLocal(global::FontWeave.Core.DataField.None, 0{tail}";
        writer.Line($"status = TryEvaluateScalar{raw.Name}Position(out ulong countPosition, out diagnostic);");
        writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
        return $"Location.AtLocal((global::FontWeave.Core.DataField){raw.FieldId}, countPosition{tail}";
    }

    private static ArrayModel FindArray(TableModel model, string name)
    {
        foreach (ArrayModel array in model.Arrays)
            if (array.Name == name) return array;
        throw new InvalidOperationException($"Array '{name}' was not found in '{model.Name}'.");
    }

    private static ScalarModel FindArrayField(ArrayModel array, string name)
    {
        foreach (ScalarModel field in array.Fields)
            if (field.Name == name) return field;
        throw new InvalidOperationException($"Field '{name}' was not found in array '{array.Name}'.");
    }

    private static string U(ulong value) => value.ToString(CultureInfo.InvariantCulture) + "UL";
    private static string U(int value) => ((ulong)value).ToString(CultureInfo.InvariantCulture) + "UL";

    private sealed class CodeWriter
    {
        private readonly StringBuilder _builder = new();
        public int Indent { get; set; }

        public void Line(string text = "")
        {
            if (text.Length != 0) _builder.Append(' ', Indent * 4).Append(text);
            _builder.Append('\n');
        }

        public override string ToString() => _builder.ToString();
    }
