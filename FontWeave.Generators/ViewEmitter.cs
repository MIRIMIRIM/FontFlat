using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Globalization;
using System.Linq;
using System.Text;

namespace FontWeave.Generators;

internal static class ViewEmitter
{
    public static string Emit(TableModel model)
    {
        if (model is null) throw new ArgumentNullException(nameof(model));

        var writer = new CodeWriter();
        writer.Line("// <auto-generated/>");
        writer.Line("#nullable enable");
        if (model.Namespace.Length != 0)
        {
            writer.Line($"namespace {model.Namespace}");
            writer.Line("{");
            writer.Indent++;
        }

        writer.Line($"public readonly ref partial struct {model.Name}");
        writer.Line("{");
        writer.Indent++;
        writer.Line("private readonly global::System.ReadOnlySpan<byte> _data;");
        writer.Line("private readonly global::FontWeave.Core.DataLocation _location;");
        writer.Line("private readonly bool _bound;");
        writer.Line();
        writer.Line($"private {model.Name}(global::System.ReadOnlySpan<byte> data, global::FontWeave.Core.DataLocation location)");
        writer.Line("{");
        writer.Indent++;
        writer.Line("_data = data;");
        writer.Line("_location = location;");
        writer.Line("_bound = true;");
        writer.Indent--;
        writer.Line("}");
        writer.Line();
        writer.Line("public bool IsBound => _bound;");
        writer.Line("public global::System.ReadOnlySpan<byte> RawBytes => IsBound");
        writer.Indent++;
        writer.Line("? _data");
        writer.Line($": throw new global::System.InvalidOperationException(\"{model.Name} is unbound.\");");
        writer.Indent--;

        foreach (ScalarModel scalar in model.Scalars)
            EmitDirectGetter(writer, model, scalar);

        writer.Line();
        EmitTryOpen(writer, model);

        foreach (ScalarModel scalar in model.Scalars)
        {
            writer.Line();
            EmitScalarPosition(writer, scalar);
            writer.Line();
            EmitScalar(writer, model, scalar);
            if (scalar.WhenVersion < 0 && scalar.Position.Base is null && scalar.Position.Count is null)
            {
                writer.Line();
                EmitScalarWrite(writer, scalar);
            }
            if (scalar.Semantic == NumberSemantic.FixedPoint)
            {
                writer.Line();
                EmitFixedPointValue(writer, scalar);
            }
        }

        foreach (DerivedModel derived in model.Derived)
        {
            writer.Line();
            EmitDerived(writer, model, derived);
        }

        foreach (ComputedModel computed in model.Computed)
        {
            writer.Line();
            EmitComputed(writer, model, computed);
        }

        foreach (ArrayModel array in model.Arrays)
        {
            writer.Line();
            EmitArrayRecord(writer, array);
            writer.Line();
            EmitRecordWrite(writer, array);
            writer.Line();
            if (array.ExternallyPositioned)
                EmitExternallyPositionedRecord(writer, model, array);
            else
            {
                EmitArrayStart(writer, array);
                writer.Line();
                if (model.ContractVersion == 1)
                {
                    EmitArrayV1(writer, model, array);
                    writer.Line();
                    EmitArrayExtent(writer, model, array);
                    writer.Line();
                    EmitRequireArrayExtent(writer, model, array);
                    if (HasCountedWriter(model, array))
                    {
                        writer.Line();
                        EmitCountedRecordWrite(writer, model, array);
                    }
                }
                else
                    EmitArray(writer, model, array);
            }
        }

        foreach (PayloadModel payload in model.Payloads)
        {
            writer.Line();
            EmitPayload(writer, model, payload);
            if (model.ContractVersion == 1)
            {
                // Spec 5.1 (card OQ-7): the V1 location overload beside the untouched
                // legacy overload; V0 payload tables keep their emitted text unchanged.
                writer.Line();
                EmitPayloadLocationOverload(writer, model, payload);
            }
        }

        foreach (ReferenceModel reference in model.References)
        {
            // A targetless reference declares no typed opener or fixup helper (spec 3.3).
            if (reference.TargetFullName is null) continue;
            writer.Line();
            EmitReferenceOpener(writer, model, reference);
            writer.Line();
            EmitReferenceFixup(writer, model, reference);
        }

        if (ScanEnabled(model))
        {
            writer.Line();
            EmitScanFamily(writer, model);
        }

        writer.Line();
        EmitKnownVersion(writer, model);
        writer.Line();
        EmitRuntimeHelpers(writer, model);

        writer.Indent--;
        writer.Line("}");
        if (model.Namespace.Length != 0)
        {
            writer.Indent--;
            writer.Line("}");
        }
        return writer.ToString();
    }

    private static void EmitDirectGetter(CodeWriter writer, TableModel model, ScalarModel scalar)
    {
        if (scalar.WhenVersion >= 0 || scalar.Position.Base is not null ||
            scalar.Position.Count is not null ||
            scalar.Position.Constant + (ulong)scalar.Width > (ulong)model.MinimumHeader)
            return;

        writer.Line();
        writer.Line($"public {scalar.CsType} {scalar.Name}");
        writer.Line("{");
        writer.Indent++;
        writer.Line("get");
        writer.Line("{");
        writer.Indent++;
        writer.Line($"if (!IsBound) throw new global::System.InvalidOperationException(\"{model.Name} is unbound.\");");
        writer.Line($"return {ReadExpression(scalar, "_data", scalar.Position.Constant)};");
        writer.Indent--;
        writer.Line("}");
        writer.Indent--;
        writer.Line("}");
    }

    private static void EmitTryOpen(CodeWriter writer, TableModel model)
    {
        writer.Line($"public static global::FontWeave.Core.ReadStatus TryOpen(global::System.ReadOnlySpan<byte> data, out {model.Name} view,");
        writer.Indent++;
        writer.Line("out global::FontWeave.Core.FontDiagnostic diagnostic,");
        writer.Line("global::FontWeave.Core.DataLocation location = default)");
        writer.Indent--;
        writer.Line("{");
        writer.Indent++;
        writer.Line("view = default;");
        writer.Line("location = NormalizeLocation(location);");
        writer.Line($"if (data.Length < {model.MinimumHeader})");
        writer.Line("{");
        writer.Indent++;
        // Use the declared fixed header fields to identify the first incomplete value.
        // Semantic partials must not need a second TryOpen just to recover this provenance.
        foreach (ScalarModel scalar in model.Scalars.OrderBy(static field => field.Position.Constant))
        {
            if (scalar.WhenVersion >= 0 || scalar.Position.Base is not null ||
                scalar.Position.Count is not null ||
                scalar.Position.Constant + (ulong)scalar.Width > (ulong)model.MinimumHeader)
                continue;
            ulong end = scalar.Position.Constant + (ulong)scalar.Width;
            writer.Line($"if ((ulong)data.Length < {U(end)})");
            writer.Indent++;
            writer.Line("return Fail(global::FontWeave.Core.ReadStatus.Truncated,");
            writer.Indent++;
            writer.Line("global::FontWeave.Core.DiagnosticCode.TruncatedData,");
            writer.Line($"location.AtLocal((global::FontWeave.Core.DataField){scalar.FieldId}, {U(scalar.Position.Constant)}),");
            writer.Line($"out diagnostic, (ulong)data.Length, {U(end)});");
            writer.Indent -= 2;
        }
        writer.Line("return Fail(global::FontWeave.Core.ReadStatus.Truncated,");
        writer.Indent++;
        writer.Line("global::FontWeave.Core.DiagnosticCode.TruncatedData,");
        writer.Line("location.AtLocal(global::FontWeave.Core.DataField.None, 0), out diagnostic,");
        writer.Line($"(ulong)data.Length, {U(model.MinimumHeader)});");
        writer.Indent -= 2;
        writer.Line("}");
        writer.Line($"view = new {model.Name}(data, location);");
        writer.Line("diagnostic = default;");
        writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
        writer.Indent--;
        writer.Line("}");
    }

    private static void EmitScalarPosition(CodeWriter writer, ScalarModel scalar)
    {
        writer.Line($"private global::FontWeave.Core.ReadStatus TryEvaluateScalar{scalar.Name}Position(out ulong position,");
        writer.Indent++;
        writer.Line("out global::FontWeave.Core.FontDiagnostic diagnostic)");
        writer.Indent--;
        writer.Line("{");
        writer.Indent++;
        EmitPosition(writer, scalar.Position, "position");
        writer.Line("diagnostic = default;");
        writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
        writer.Indent--;
        writer.Line("}");
    }

    private static void EmitScalar(CodeWriter writer, TableModel model, ScalarModel scalar)
    {
        writer.Line($"public global::FontWeave.Core.ReadStatus TryGet{scalar.Name}(out {scalar.CsType} value,");
        writer.Indent++;
        writer.Line("out global::FontWeave.Core.FontDiagnostic diagnostic)");
        writer.Indent--;
        writer.Line("{");
        writer.Indent++;
        writer.Line("value = default;");
        writer.Line("if (!IsBound)");
        writer.Indent++;
        writer.Line("return Fail(global::FontWeave.Core.ReadStatus.Uninitialized,");
        writer.Indent++;
        writer.Line("global::FontWeave.Core.DiagnosticCode.UnboundView,");
        writer.Line($"Location.AtLocal((global::FontWeave.Core.DataField){scalar.FieldId}, {U(scalar.Position.Constant)}), out diagnostic);");
        writer.Indent -= 2;

        if (scalar.WhenVersion >= 0)
        {
            writer.Line("global::FontWeave.Core.ReadStatus status = TryRequireKnownVersion(out ulong version, out diagnostic);");
            writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
            writer.Line($"if (version != {U((ulong)scalar.WhenVersion)})");
            writer.Line("{");
            writer.Indent++;
            writer.Line($"value = ({scalar.CsType}){U(scalar.Otherwise)};");
            writer.Line("diagnostic = default;");
            writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
            writer.Indent--;
            writer.Line("}");
        }

        writer.Line($"global::FontWeave.Core.ReadStatus positionStatus = TryEvaluateScalar{scalar.Name}Position(out ulong position, out diagnostic);");
        writer.Line("if (positionStatus != global::FontWeave.Core.ReadStatus.Done) return positionStatus;");
        writer.Line($"if (!TrySlice(_data, position, {U(scalar.Width)}, out global::System.ReadOnlySpan<byte> bytes))");
        writer.Indent++;
        writer.Line("return Fail(global::FontWeave.Core.ReadStatus.Truncated,");
        writer.Indent++;
        writer.Line("global::FontWeave.Core.DiagnosticCode.TruncatedData,");
        writer.Line($"Location.AtLocal((global::FontWeave.Core.DataField){scalar.FieldId}, position), out diagnostic,");
        writer.Line($"(ulong)_data.Length, position + {U(scalar.Width)});");
        writer.Indent -= 2;
        writer.Line($"value = {ReadExpression(scalar, "bytes", 0)};");
        writer.Line("diagnostic = default;");
        writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
        writer.Indent--;
        writer.Line("}");
    }

    private static void EmitFixedPointValue(CodeWriter writer, ScalarModel scalar)
    {
        writer.Line($"public global::FontWeave.Core.ReadStatus TryGet{scalar.Name}Value(out double value,");
        writer.Indent++;
        writer.Line("out global::FontWeave.Core.FontDiagnostic diagnostic)");
        writer.Indent--;
        writer.Line("{");
        writer.Indent++;
        writer.Line("value = default;");
        writer.Line($"global::FontWeave.Core.ReadStatus status = TryGet{scalar.Name}(out {scalar.CsType} raw, out diagnostic);");
        writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
        writer.Line($"value = (double)raw / {U(scalar.Scale)};");
        writer.Line("diagnostic = default;");
        writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
        writer.Indent--;
        writer.Line("}");
    }

    // These helpers only encode schema-covered wire fields. Semantic compilers retain
    // version selection, layout planning, admission, canonical policy and publication.
    private static void EmitScalarWrite(CodeWriter writer, ScalarModel scalar)
    {
        writer.Line($"internal static global::FontWeave.Core.ReadStatus TryWrite{scalar.Name}(global::System.Span<byte> destination, {scalar.CsType} value,");
        writer.Indent++;
        writer.Line("out global::FontWeave.Core.FontDiagnostic diagnostic, global::FontWeave.Core.DataLocation location = default)");
        writer.Indent--;
        writer.Line("{");
        writer.Indent++;
        writer.Line("location = NormalizeLocation(location);");
        writer.Line($"if (!TrySlice(destination, {U(scalar.Position.Constant)}, {U(scalar.Width)}, out _))");
        writer.Indent++;
        writer.Line("return Fail(global::FontWeave.Core.ReadStatus.DestinationTooSmall, global::FontWeave.Core.DiagnosticCode.DestinationTooSmall,");
        writer.Indent++;
        writer.Line($"location.AtLocal((global::FontWeave.Core.DataField){scalar.FieldId}, {U(scalar.Position.Constant)}), out diagnostic,");
        writer.Line($"(ulong)destination.Length, {U(scalar.Position.Constant + (ulong)scalar.Width)});");
        writer.Indent -= 2;
        if (scalar.Type == WireType.UInt24)
        {
            EmitUInt24Guard(writer, scalar, "value", U(scalar.Position.Constant));
            // Slice first so an accepted high offset never becomes an invalid C#
            // byte-index constant, even when the destination preflight always refuses it.
            writer.Line($"global::System.Span<byte> bytes = destination.Slice({scalar.Position.Constant}, {scalar.Width});");
            EmitWriteValue(writer, scalar, "bytes", "value", 0);
        }
        else
            EmitWriteValue(writer, scalar, "destination", "value", scalar.Position.Constant);
        writer.Line("diagnostic = default;");
        writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
        writer.Indent--;
        writer.Line("}");
    }

    private static void EmitRecordWrite(CodeWriter writer, ArrayModel array)
    {
        writer.Line($"internal static global::FontWeave.Core.ReadStatus TryWrite{array.Name}At(global::System.Span<byte> destination, ulong rowPosition, in {array.Name}Data record,");
        writer.Indent++;
        writer.Line("out global::FontWeave.Core.FontDiagnostic diagnostic, global::FontWeave.Core.DataLocation location = default)");
        writer.Indent--;
        writer.Line("{");
        writer.Indent++;
        writer.Line("location = NormalizeLocation(location);");
        writer.Line($"if (!TrySlice(destination, rowPosition, {U(array.Stride)}, out _))");
        writer.Indent++;
        writer.Line("return Fail(global::FontWeave.Core.ReadStatus.DestinationTooSmall, global::FontWeave.Core.DiagnosticCode.DestinationTooSmall,");
        writer.Indent++;
        writer.Line("location.AtLocal(global::FontWeave.Core.DataField.OutputBytes, rowPosition, record.Ordinal), out diagnostic,");
        writer.Line($"(ulong)destination.Length, rowPosition > ulong.MaxValue - {U(array.Stride)} ? ulong.MaxValue : rowPosition + {U(array.Stride)});");
        writer.Indent -= 2;
        // Check every narrow value before touching a row, even when the invalid value
        // follows valid fields. Padding is not a declared field and is left untouched.
        foreach (ScalarModel field in array.Fields)
            if (field.Type == WireType.UInt24)
            {
                string position = $"rowPosition + {U(field.Position.Constant)}";
                EmitUInt24Guard(writer, field, "record." + field.Name, position, "record.Ordinal");
            }
        writer.Line($"global::System.Span<byte> row = destination.Slice((int)rowPosition, {array.Stride});");
        foreach (ScalarModel field in array.Fields)
            EmitWriteValue(writer, field, "row", "record." + field.Name, field.Position.Constant);
        writer.Line("diagnostic = default;");
        writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
        writer.Indent--;
        writer.Line("}");
    }

    private static void EmitUInt24Guard(CodeWriter writer, ScalarModel field, string value,
        string position, string ordinal = "-1")
    {
        writer.Line($"if ({value} > 0xFFFFFFu)");
        writer.Indent++;
        writer.Line("return Fail(global::FontWeave.Core.ReadStatus.InvalidFormat, global::FontWeave.Core.DiagnosticCode.InvalidValue,");
        writer.Indent++;
        writer.Line($"location.AtLocal((global::FontWeave.Core.DataField){field.FieldId}, {position}, {ordinal}), out diagnostic, {value}, 0xFFFFFFu);");
        writer.Indent -= 2;
    }

    private static void EmitWriteValue(CodeWriter writer, ScalarModel field, string bytes,
        string value, ulong offset)
    {
        if (field.Type is WireType.UInt8 or WireType.Int8)
        {
            writer.Line($"{bytes}[{offset}] = unchecked((byte){value});");
            return;
        }
        if (field.Type == WireType.UInt24)
        {
            for (int i = 0; i < 3; i++)
            {
                int shift = (field.Endian == WireEndian.Big ? 2 - i : i) * 8;
                writer.Line($"{bytes}[{offset + (uint)i}] = unchecked((byte)({value} >> {shift}));");
            }
            return;
        }
        string suffix = field.Endian == WireEndian.Big ? "BigEndian" : "LittleEndian";
        string type = field.Type switch
        {
            WireType.UInt16 => "UInt16", WireType.UInt32 => "UInt32", WireType.Int16 => "Int16",
            WireType.Int64 => "Int64", _ => "Int32",
        };
        writer.Line($"global::System.Buffers.Binary.BinaryPrimitives.Write{type}{suffix}({bytes}.Slice({offset}, {field.Width}), {value});");
    }

    private static void EmitDerived(CodeWriter writer, TableModel model, DerivedModel derived)
    {
        writer.Line($"public global::FontWeave.Core.ReadStatus TryGet{derived.Name}(out ulong value,");
        writer.Indent++;
        writer.Line("out global::FontWeave.Core.FontDiagnostic diagnostic)");
        writer.Indent--;
        writer.Line("{");
        writer.Indent++;
        writer.Line("value = default;");
        writer.Line("if (!IsBound)");
        writer.Indent++;
        writer.Line("return Fail(global::FontWeave.Core.ReadStatus.Uninitialized,");
        writer.Indent++;
        writer.Line("global::FontWeave.Core.DiagnosticCode.UnboundView,");
        writer.Line("Location.AtLocal(global::FontWeave.Core.DataField.None, 0), out diagnostic);");
        writer.Indent -= 2;

        if (derived.WhenVersion >= 0)
        {
            writer.Line("global::FontWeave.Core.ReadStatus status = TryRequireKnownVersion(out ulong version, out diagnostic);");
            writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
            writer.Line($"if (version != {U((ulong)derived.WhenVersion)})");
            writer.Line("{");
            writer.Indent++;
            writer.Line($"status = TryGet{derived.Otherwise}(out var otherwiseValue, out diagnostic);");
            writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
            writer.Line("value = (ulong)otherwiseValue;");
            writer.Line("diagnostic = default;");
            writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
            writer.Indent--;
            writer.Line("}");
        }

        EmitPosition(writer, derived.Expression, "value", derived.CountSubtract,
            derived.Expression.Count is { } countName ? FindScalarOrNull(model, countName)?.FieldId ?? 0 : 0);
        writer.Line("diagnostic = default;");
        writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
        writer.Indent--;
        writer.Line("}");
    }

    // Spec 2.3 computed contract (card 1.2-a/1.5): unbound → known version → condition →
    // inputs in declared order (each through its own getter, failures propagate) → hook →
    // Maximum. The diagnostic location is the declared DiagnosticSource position (or the
    // owner start) carrying the declared DiagnosticField; failures leave value at 0.
    private static void EmitComputed(CodeWriter writer, TableModel model, ComputedModel computed)
    {
        writer.Line($"public global::FontWeave.Core.ReadStatus TryGet{computed.Name}(out ulong value,");
        writer.Indent++;
        writer.Line("out global::FontWeave.Core.FontDiagnostic diagnostic)");
        writer.Indent--;
        writer.Line("{");
        writer.Indent++;
        writer.Line("value = default;");
        writer.Line("if (!IsBound)");
        writer.Indent++;
        writer.Line("return Fail(global::FontWeave.Core.ReadStatus.Uninitialized,");
        writer.Indent++;
        writer.Line("global::FontWeave.Core.DiagnosticCode.UnboundView,");
        writer.Line("Location.AtLocal(global::FontWeave.Core.DataField.None, 0), out diagnostic);");
        writer.Indent -= 2;

        bool statusDeclared = false;
        if (model.VersionField is not null)
        {
            statusDeclared = true;
            if (computed.WhenVersions.Length != 0)
            {
                writer.Line("global::FontWeave.Core.ReadStatus status = TryRequireKnownVersion(out ulong version, out diagnostic);");
                writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
                EmitCondition(writer, model, computed.WhenVersions);
            }
            else
            {
                writer.Line("global::FontWeave.Core.ReadStatus status = TryRequireKnownVersion(out _, out diagnostic);");
                writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
            }
        }
        var arguments = new StringBuilder();
        for (int i = 0; i < computed.Inputs.Length; i++)
        {
            string input = computed.Inputs[i];
            if (i != 0) arguments.Append(", ");
            if (input == "@length")
            {
                writer.Line($"int length{i} = _data.Length;");
                arguments.Append("length").Append(i);
                continue;
            }
            string csType = FindScalarOrNull(model, input)?.CsType ?? "ulong";
            if (statusDeclared)
                writer.Line($"status = TryGet{input}(out {csType} input{i}, out diagnostic);");
            else
            {
                statusDeclared = true;
                writer.Line($"global::FontWeave.Core.ReadStatus status = TryGet{input}(out {csType} input{i}, out diagnostic);");
            }
            writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
            arguments.Append("input").Append(i);
        }
        string location;
        if (computed.DiagnosticSource is { } source)
        {
            if (statusDeclared)
                writer.Line($"status = TryEvaluateScalar{source}Position(out ulong sourcePosition, out diagnostic);");
            else
            {
                statusDeclared = true;
                writer.Line($"global::FontWeave.Core.ReadStatus status = TryEvaluateScalar{source}Position(out ulong sourcePosition, out diagnostic);");
            }
            writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
            location = $"Location.AtLocal((global::FontWeave.Core.DataField){computed.DiagnosticFieldId}, sourcePosition)";
        }
        else
            location = $"Location.AtLocal((global::FontWeave.Core.DataField){computed.DiagnosticFieldId}, 0)";
        writer.Line($"var diagnosticLocation = {location};");
        string hookStatus = statusDeclared ? "status" : "global::FontWeave.Core.ReadStatus status";
        string hookArguments = arguments.Length == 0 ? "" : arguments + ", ";
        writer.Line($"{hookStatus} = {computed.Method}({hookArguments}diagnosticLocation, out ulong hookValue, out diagnostic);");
        writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
        writer.Line($"if (hookValue > {U(computed.Maximum)})");
        writer.Line("{");
        writer.Indent++;
        writer.Line("return Fail(global::FontWeave.Core.ReadStatus.InvalidFormat,");
        writer.Indent++;
        writer.Line("global::FontWeave.Core.DiagnosticCode.InvalidValue,");
        writer.Line($"diagnosticLocation, out diagnostic, hookValue, {U(computed.Maximum)});");
        writer.Indent -= 2;
        writer.Line("}");
        writer.Line("value = hookValue;");
        writer.Line("diagnostic = default;");
        writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
        writer.Indent--;
        writer.Line("}");
    }

    // A declared WhenVersions domain refuses known-but-inactive versions before any
    // count, ordinal or extent evaluation (card 1.2-b/1.5, OQ-2): UnsupportedOperation
    // located at the version field with Detail=version and Expected=0.
    private static void EmitCondition(CodeWriter writer, TableModel model, ImmutableArray<uint> whenVersions)
    {
        var inactive = new StringBuilder();
        for (int i = 0; i < whenVersions.Length; i++)
        {
            if (i != 0) inactive.Append(" && ");
            inactive.Append("version != ").Append(U(whenVersions[i]));
        }
        ScalarModel versionField = FindScalar(model, model.VersionField!);
        writer.Line($"if ({inactive})");
        writer.Line("{");
        writer.Indent++;
        writer.Line($"status = TryEvaluateScalar{versionField.Name}Position(out ulong versionPosition, out diagnostic);");
        writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
        writer.Line("return Fail(global::FontWeave.Core.ReadStatus.UnsupportedFormat,");
        writer.Indent++;
        writer.Line("global::FontWeave.Core.DiagnosticCode.UnsupportedOperation,");
        writer.Line($"Location.AtLocal((global::FontWeave.Core.DataField){versionField.FieldId}, versionPosition),");
        writer.Line("out diagnostic, version, 0);");
        writer.Indent -= 2;
        writer.Line("}");
    }

    private static void EmitArrayRecord(CodeWriter writer, ArrayModel array)
    {
        var parameters = new StringBuilder("int Ordinal");
        foreach (ScalarModel field in array.Fields)
            parameters.Append(", ").Append(field.CsType).Append(' ').Append(field.Name);
        writer.Line($"public readonly record struct {array.Name}Data({parameters});");
    }

    private static void EmitExternallyPositionedRecord(CodeWriter writer, TableModel model, ArrayModel array)
    {
        writer.Line($"private global::FontWeave.Core.ReadStatus TryRead{array.Name}At(ulong rowPosition, int ordinal,");
        writer.Indent++;
        writer.Line($"out {array.Name}Data record, out global::FontWeave.Core.FontDiagnostic diagnostic)");
        writer.Indent--;
        writer.Line("{");
        writer.Indent++;
        writer.Line("record = default;");
        writer.Line("if (!IsBound)");
        writer.Indent++;
        writer.Line("return Fail(global::FontWeave.Core.ReadStatus.Uninitialized,");
        writer.Indent++;
        writer.Line("global::FontWeave.Core.DiagnosticCode.UnboundView,");
