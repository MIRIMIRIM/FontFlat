using System;
using System.Globalization;
using System.Linq;
using System.Text;

namespace FontWeave.Generators;

internal static class ViewEmitter
{
    public static string Emit(TableModel model)
    {
        if (model is null) throw new ArgumentNullException(nameof(model));

        var writer = new CodeWriter();
        writer.Line("// <auto-generated/>");
        writer.Line("#nullable enable");
        if (model.Namespace.Length != 0)
        {
            writer.Line($"namespace {model.Namespace}");
            writer.Line("{");
            writer.Indent++;
        }

        writer.Line($"public readonly ref partial struct {model.Name}");
        writer.Line("{");
        writer.Indent++;
        writer.Line("private readonly global::System.ReadOnlySpan<byte> _data;");
        writer.Line("private readonly global::FontWeave.Core.DataLocation _location;");
        writer.Line("private readonly bool _bound;");
        writer.Line();
        writer.Line($"private {model.Name}(global::System.ReadOnlySpan<byte> data, global::FontWeave.Core.DataLocation location)");
        writer.Line("{");
        writer.Indent++;
        writer.Line("_data = data;");
        writer.Line("_location = location;");
        writer.Line("_bound = true;");
        writer.Indent--;
        writer.Line("}");
        writer.Line();
        writer.Line("public bool IsBound => _bound;");
        writer.Line("public global::System.ReadOnlySpan<byte> RawBytes => IsBound");
        writer.Indent++;
        writer.Line("? _data");
        writer.Line($": throw new global::System.InvalidOperationException(\"{model.Name} is unbound.\");");
        writer.Indent--;

        foreach (ScalarModel scalar in model.Scalars)
            EmitDirectGetter(writer, model, scalar);

        writer.Line();
        EmitTryOpen(writer, model);

        foreach (ScalarModel scalar in model.Scalars)
        {
            writer.Line();
            EmitScalarPosition(writer, scalar);
            writer.Line();
            EmitScalar(writer, model, scalar);
            if (scalar.WhenVersion < 0 && scalar.Position.Base is null && scalar.Position.Count is null)
            {
                writer.Line();
                EmitScalarWrite(writer, scalar);
            }
            if (scalar.Semantic == NumberSemantic.FixedPoint)
            {
                writer.Line();
                EmitFixedPointValue(writer, scalar);
            }
        }

        foreach (DerivedModel derived in model.Derived)
        {
            writer.Line();
            EmitDerived(writer, model, derived);
        }

        foreach (ArrayModel array in model.Arrays)
        {
            writer.Line();
            EmitArrayRecord(writer, array);
            writer.Line();
            EmitRecordWrite(writer, array);
            writer.Line();
            if (array.ExternallyPositioned)
                EmitExternallyPositionedRecord(writer, array);
            else
            {
                EmitArrayStart(writer, array);
                writer.Line();
                EmitArray(writer, model, array);
            }
        }

        foreach (PayloadModel payload in model.Payloads)
        {
            writer.Line();
            EmitPayload(writer, model, payload);
        }

        writer.Line();
        EmitKnownVersion(writer, model);
        writer.Line();
        EmitRuntimeHelpers(writer, model);

        writer.Indent--;
        writer.Line("}");
        if (model.Namespace.Length != 0)
        {
            writer.Indent--;
            writer.Line("}");
        }
        return writer.ToString();
    }

    private static void EmitDirectGetter(CodeWriter writer, TableModel model, ScalarModel scalar)
    {
        if (scalar.WhenVersion >= 0 || scalar.Position.Base is not null ||
            scalar.Position.Count is not null ||
            scalar.Position.Constant + (ulong)scalar.Width > (ulong)model.MinimumHeader)
            return;

        writer.Line();
        writer.Line($"public {scalar.CsType} {scalar.Name}");
        writer.Line("{");
        writer.Indent++;
        writer.Line("get");
        writer.Line("{");
        writer.Indent++;
        writer.Line($"if (!IsBound) throw new global::System.InvalidOperationException(\"{model.Name} is unbound.\");");
        writer.Line($"return {ReadExpression(scalar, "_data", scalar.Position.Constant)};");
        writer.Indent--;
        writer.Line("}");
        writer.Indent--;
        writer.Line("}");
    }

    private static void EmitTryOpen(CodeWriter writer, TableModel model)
    {
        writer.Line($"public static global::FontWeave.Core.ReadStatus TryOpen(global::System.ReadOnlySpan<byte> data, out {model.Name} view,");
        writer.Indent++;
        writer.Line("out global::FontWeave.Core.FontDiagnostic diagnostic,");
        writer.Line("global::FontWeave.Core.DataLocation location = default)");
        writer.Indent--;
        writer.Line("{");
        writer.Indent++;
        writer.Line("view = default;");
        writer.Line("location = NormalizeLocation(location);");
        writer.Line($"if (data.Length < {model.MinimumHeader})");
        writer.Line("{");
        writer.Indent++;
        // Use the declared fixed header fields to identify the first incomplete value.
        // Semantic partials must not need a second TryOpen just to recover this provenance.
        foreach (ScalarModel scalar in model.Scalars.OrderBy(static field => field.Position.Constant))
        {
            if (scalar.WhenVersion >= 0 || scalar.Position.Base is not null ||
                scalar.Position.Count is not null ||
                scalar.Position.Constant + (ulong)scalar.Width > (ulong)model.MinimumHeader)
                continue;
            ulong end = scalar.Position.Constant + (ulong)scalar.Width;
            writer.Line($"if ((ulong)data.Length < {U(end)})");
            writer.Indent++;
            writer.Line("return Fail(global::FontWeave.Core.ReadStatus.Truncated,");
            writer.Indent++;
            writer.Line("global::FontWeave.Core.DiagnosticCode.TruncatedData,");
            writer.Line($"location.AtLocal((global::FontWeave.Core.DataField){scalar.FieldId}, {U(scalar.Position.Constant)}),");
            writer.Line($"out diagnostic, (ulong)data.Length, {U(end)});");
            writer.Indent -= 2;
        }
        writer.Line("return Fail(global::FontWeave.Core.ReadStatus.Truncated,");
        writer.Indent++;
        writer.Line("global::FontWeave.Core.DiagnosticCode.TruncatedData,");
        writer.Line("location.AtLocal(global::FontWeave.Core.DataField.None, 0), out diagnostic,");
        writer.Line($"(ulong)data.Length, {U(model.MinimumHeader)});");
        writer.Indent -= 2;
        writer.Line("}");
        writer.Line($"view = new {model.Name}(data, location);");
        writer.Line("diagnostic = default;");
        writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
        writer.Indent--;
        writer.Line("}");
    }

    private static void EmitScalarPosition(CodeWriter writer, ScalarModel scalar)
    {
        writer.Line($"private global::FontWeave.Core.ReadStatus TryEvaluateScalar{scalar.Name}Position(out ulong position,");
        writer.Indent++;
        writer.Line("out global::FontWeave.Core.FontDiagnostic diagnostic)");
        writer.Indent--;
        writer.Line("{");
        writer.Indent++;
        EmitPosition(writer, scalar.Position, "position");
        writer.Line("diagnostic = default;");
        writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
        writer.Indent--;
        writer.Line("}");
    }

    private static void EmitScalar(CodeWriter writer, TableModel model, ScalarModel scalar)
    {
        writer.Line($"public global::FontWeave.Core.ReadStatus TryGet{scalar.Name}(out {scalar.CsType} value,");
        writer.Indent++;
        writer.Line("out global::FontWeave.Core.FontDiagnostic diagnostic)");
        writer.Indent--;
        writer.Line("{");
        writer.Indent++;
        writer.Line("value = default;");
        writer.Line("if (!IsBound)");
        writer.Indent++;
        writer.Line("return Fail(global::FontWeave.Core.ReadStatus.Uninitialized,");
        writer.Indent++;
        writer.Line("global::FontWeave.Core.DiagnosticCode.UnboundView,");
        writer.Line($"Location.AtLocal((global::FontWeave.Core.DataField){scalar.FieldId}, {U(scalar.Position.Constant)}), out diagnostic);");
        writer.Indent -= 2;

        if (scalar.WhenVersion >= 0)
        {
            writer.Line("global::FontWeave.Core.ReadStatus status = TryRequireKnownVersion(out ulong version, out diagnostic);");
            writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
            writer.Line($"if (version != {U((ulong)scalar.WhenVersion)})");
            writer.Line("{");
            writer.Indent++;
            writer.Line($"value = ({scalar.CsType}){U(scalar.Otherwise)};");
            writer.Line("diagnostic = default;");
            writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
            writer.Indent--;
            writer.Line("}");
        }

        writer.Line($"global::FontWeave.Core.ReadStatus positionStatus = TryEvaluateScalar{scalar.Name}Position(out ulong position, out diagnostic);");
        writer.Line("if (positionStatus != global::FontWeave.Core.ReadStatus.Done) return positionStatus;");
        writer.Line($"if (!TrySlice(_data, position, {U(scalar.Width)}, out global::System.ReadOnlySpan<byte> bytes))");
        writer.Indent++;
        writer.Line("return Fail(global::FontWeave.Core.ReadStatus.Truncated,");
        writer.Indent++;
        writer.Line("global::FontWeave.Core.DiagnosticCode.TruncatedData,");
        writer.Line($"Location.AtLocal((global::FontWeave.Core.DataField){scalar.FieldId}, position), out diagnostic,");
        writer.Line($"(ulong)_data.Length, position + {U(scalar.Width)});");
        writer.Indent -= 2;
        writer.Line($"value = {ReadExpression(scalar, "bytes", 0)};");
        writer.Line("diagnostic = default;");
        writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
        writer.Indent--;
        writer.Line("}");
    }

    private static void EmitFixedPointValue(CodeWriter writer, ScalarModel scalar)
    {
        writer.Line($"public global::FontWeave.Core.ReadStatus TryGet{scalar.Name}Value(out double value,");
        writer.Indent++;
        writer.Line("out global::FontWeave.Core.FontDiagnostic diagnostic)");
        writer.Indent--;
        writer.Line("{");
        writer.Indent++;
        writer.Line("value = default;");
        writer.Line($"global::FontWeave.Core.ReadStatus status = TryGet{scalar.Name}(out {scalar.CsType} raw, out diagnostic);");
        writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
        writer.Line($"value = (double)raw / {U(scalar.Scale)};");
        writer.Line("diagnostic = default;");
        writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
        writer.Indent--;
        writer.Line("}");
    }

    // These helpers only encode schema-covered wire fields. Semantic compilers retain
    // version selection, layout planning, admission, canonical policy and publication.
    private static void EmitScalarWrite(CodeWriter writer, ScalarModel scalar)
    {
        writer.Line($"internal static global::FontWeave.Core.ReadStatus TryWrite{scalar.Name}(global::System.Span<byte> destination, {scalar.CsType} value,");
        writer.Indent++;
        writer.Line("out global::FontWeave.Core.FontDiagnostic diagnostic, global::FontWeave.Core.DataLocation location = default)");
        writer.Indent--;
        writer.Line("{");
        writer.Indent++;
        writer.Line("location = NormalizeLocation(location);");
        writer.Line($"if (!TrySlice(destination, {U(scalar.Position.Constant)}, {U(scalar.Width)}, out _))");
        writer.Indent++;
        writer.Line("return Fail(global::FontWeave.Core.ReadStatus.DestinationTooSmall, global::FontWeave.Core.DiagnosticCode.DestinationTooSmall,");
        writer.Indent++;
        writer.Line($"location.AtLocal((global::FontWeave.Core.DataField){scalar.FieldId}, {U(scalar.Position.Constant)}), out diagnostic,");
        writer.Line($"(ulong)destination.Length, {U(scalar.Position.Constant + (ulong)scalar.Width)});");
        writer.Indent -= 2;
        EmitWriteValue(writer, scalar, "destination", "value", scalar.Position.Constant);
        writer.Line("diagnostic = default;");
        writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
        writer.Indent--;
        writer.Line("}");
    }

    private static void EmitRecordWrite(CodeWriter writer, ArrayModel array)
    {
        writer.Line($"internal static global::FontWeave.Core.ReadStatus TryWrite{array.Name}At(global::System.Span<byte> destination, ulong rowPosition, in {array.Name}Data record,");
        writer.Indent++;
        writer.Line("out global::FontWeave.Core.FontDiagnostic diagnostic, global::FontWeave.Core.DataLocation location = default)");
        writer.Indent--;
        writer.Line("{");
        writer.Indent++;
        writer.Line("location = NormalizeLocation(location);");
        writer.Line($"if (!TrySlice(destination, rowPosition, {U(array.Stride)}, out _))");
        writer.Indent++;
        writer.Line("return Fail(global::FontWeave.Core.ReadStatus.DestinationTooSmall, global::FontWeave.Core.DiagnosticCode.DestinationTooSmall,");
        writer.Indent++;
        writer.Line("location.AtLocal(global::FontWeave.Core.DataField.OutputBytes, rowPosition, record.Ordinal), out diagnostic,");
        writer.Line($"(ulong)destination.Length, rowPosition > ulong.MaxValue - {U(array.Stride)} ? ulong.MaxValue : rowPosition + {U(array.Stride)});");
        writer.Indent -= 2;
        // Padding is not a declared field and is left untouched.
        writer.Line($"global::System.Span<byte> row = destination.Slice((int)rowPosition, {array.Stride});");
        foreach (ScalarModel field in array.Fields)
            EmitWriteValue(writer, field, "row", "record." + field.Name, field.Position.Constant);
        writer.Line("diagnostic = default;");
        writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
        writer.Indent--;
        writer.Line("}");
    }

    private static void EmitWriteValue(CodeWriter writer, ScalarModel field, string bytes,
        string value, ulong offset)
    {
        if (field.Type is WireType.UInt8 or WireType.Int8)
        {
            writer.Line($"{bytes}[{offset}] = unchecked((byte){value});");
            return;
        }
        string suffix = field.Endian == WireEndian.Big ? "BigEndian" : "LittleEndian";
        string type = field.Type switch
        {
            WireType.UInt16 => "UInt16", WireType.UInt32 => "UInt32", WireType.Int16 => "Int16",
            WireType.Int64 => "Int64", _ => "Int32",
        };
        writer.Line($"global::System.Buffers.Binary.BinaryPrimitives.Write{type}{suffix}({bytes}.Slice({offset}, {field.Width}), {value});");
    }

    private static void EmitDerived(CodeWriter writer, TableModel model, DerivedModel derived)
    {
        writer.Line($"public global::FontWeave.Core.ReadStatus TryGet{derived.Name}(out ulong value,");
        writer.Indent++;
        writer.Line("out global::FontWeave.Core.FontDiagnostic diagnostic)");
        writer.Indent--;
        writer.Line("{");
        writer.Indent++;
        writer.Line("value = default;");
        writer.Line("if (!IsBound)");
        writer.Indent++;
        writer.Line("return Fail(global::FontWeave.Core.ReadStatus.Uninitialized,");
        writer.Indent++;
        writer.Line("global::FontWeave.Core.DiagnosticCode.UnboundView,");
        writer.Line("Location.AtLocal(global::FontWeave.Core.DataField.None, 0), out diagnostic);");
        writer.Indent -= 2;

        if (derived.WhenVersion >= 0)
        {
            writer.Line("global::FontWeave.Core.ReadStatus status = TryRequireKnownVersion(out ulong version, out diagnostic);");
            writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
            writer.Line($"if (version != {U((ulong)derived.WhenVersion)})");
            writer.Line("{");
            writer.Indent++;
            writer.Line($"status = TryGet{derived.Otherwise}(out var otherwiseValue, out diagnostic);");
            writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
            writer.Line("value = (ulong)otherwiseValue;");
            writer.Line("diagnostic = default;");
            writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
            writer.Indent--;
            writer.Line("}");
        }

        EmitPosition(writer, derived.Expression, "value");
        writer.Line("diagnostic = default;");
        writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
        writer.Indent--;
        writer.Line("}");
    }

    private static void EmitArrayRecord(CodeWriter writer, ArrayModel array)
    {
        var parameters = new StringBuilder("int Ordinal");
        foreach (ScalarModel field in array.Fields)
            parameters.Append(", ").Append(field.CsType).Append(' ').Append(field.Name);
        writer.Line($"public readonly record struct {array.Name}Data({parameters});");
    }

    private static void EmitExternallyPositionedRecord(CodeWriter writer, ArrayModel array)
    {
        writer.Line($"private global::FontWeave.Core.ReadStatus TryRead{array.Name}At(ulong rowPosition, int ordinal,");
        writer.Indent++;
        writer.Line($"out {array.Name}Data record, out global::FontWeave.Core.FontDiagnostic diagnostic)");
        writer.Indent--;
        writer.Line("{");
        writer.Indent++;
        writer.Line("record = default;");
        writer.Line("if (!IsBound)");
        writer.Indent++;
        writer.Line("return Fail(global::FontWeave.Core.ReadStatus.Uninitialized,");
        writer.Indent++;
        writer.Line("global::FontWeave.Core.DiagnosticCode.UnboundView,");
        writer.Line("Location.AtLocal(global::FontWeave.Core.DataField.None, rowPosition, ordinal), out diagnostic);");
        writer.Indent -= 2;
        writer.Line("global::FontWeave.Core.ReadStatus status = TryRequireKnownVersion(out _, out diagnostic);");
        writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
        writer.Line($"if (!TrySlice(_data, rowPosition, {U(array.Stride)}, out global::System.ReadOnlySpan<byte> row))");
        writer.Line("{");
        writer.Indent++;
        foreach (ScalarModel field in array.Fields.OrderBy(static field => field.Position.Constant))
        {
            ulong fieldEnd = field.Position.Constant + (ulong)field.Width;
            writer.Line($"if (!TrySlice(_data, rowPosition, {U(fieldEnd)}, out _))");
            writer.Line("{");
            writer.Indent++;
            writer.Line($"ulong fieldPosition = rowPosition > ulong.MaxValue - {U(field.Position.Constant)} ? ulong.MaxValue : rowPosition + {U(field.Position.Constant)};");
            writer.Line($"ulong expectedEnd = rowPosition > ulong.MaxValue - {U(fieldEnd)} ? ulong.MaxValue : rowPosition + {U(fieldEnd)};");
            writer.Line("return Fail(global::FontWeave.Core.ReadStatus.Truncated,");
            writer.Indent++;
            writer.Line("global::FontWeave.Core.DiagnosticCode.TruncatedData,");
            writer.Line($"Location.AtLocal((global::FontWeave.Core.DataField){field.FieldId}, fieldPosition, ordinal),");
            writer.Line("out diagnostic, (ulong)_data.Length, expectedEnd);");
            writer.Indent--;
            writer.Indent--;
            writer.Line("}");
        }
        writer.Line("return Fail(global::FontWeave.Core.ReadStatus.Truncated,");
        writer.Indent++;
        writer.Line("global::FontWeave.Core.DiagnosticCode.TruncatedData,");
        writer.Line("Location.AtLocal(global::FontWeave.Core.DataField.None, rowPosition, ordinal),");
        writer.Line($"out diagnostic, (ulong)_data.Length, rowPosition > ulong.MaxValue - {U(array.Stride)} ? ulong.MaxValue : rowPosition + {U(array.Stride)});");
        writer.Indent -= 2;
        writer.Line("}");
        EmitRecordFields(writer, array);
        writer.Indent--;
        writer.Line("}");
    }

    private static void EmitArrayStart(CodeWriter writer, ArrayModel array)
    {
        writer.Line($"private global::FontWeave.Core.ReadStatus TryEvaluateArray{array.Name}Start(out ulong start,");
        writer.Indent++;
        writer.Line("out global::FontWeave.Core.FontDiagnostic diagnostic)");
        writer.Indent--;
        writer.Line("{");
        writer.Indent++;
        EmitPosition(writer, array.Start, "start");
        writer.Line("diagnostic = default;");
        writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
        writer.Indent--;
        writer.Line("}");
    }

    private static void EmitArray(CodeWriter writer, TableModel model, ArrayModel array)
    {
        ScalarModel count = FindScalar(model, array.Count);
        writer.Line($"public global::FontWeave.Core.ReadStatus TryGet{array.Name}(int ordinal,");
        writer.Indent++;
        writer.Line($"out {array.Name}Data record, out global::FontWeave.Core.FontDiagnostic diagnostic)");
        writer.Indent--;
        writer.Line("{");
        writer.Indent++;
        writer.Line("record = default;");
        writer.Line("if (!IsBound)");
        writer.Indent++;
        writer.Line("return Fail(global::FontWeave.Core.ReadStatus.Uninitialized,");
        writer.Indent++;
        writer.Line("global::FontWeave.Core.DiagnosticCode.UnboundView,");
        writer.Line("Location.AtLocal(global::FontWeave.Core.DataField.None, 0, ordinal), out diagnostic);");
        writer.Indent -= 2;
        writer.Line("global::FontWeave.Core.ReadStatus status = TryRequireKnownVersion(out _, out diagnostic);");
        writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
        writer.Line($"status = TryGet{array.Count}(out var countRaw, out diagnostic);");
        writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
        writer.Line("ulong count = (ulong)countRaw;");
        writer.Line("if (ordinal < 0 || (ulong)ordinal >= count)");
        writer.Line("{");
        writer.Indent++;
        writer.Line($"status = TryEvaluateScalar{count.Name}Position(out ulong countPosition, out diagnostic);");
        writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
        writer.Line("return Fail(global::FontWeave.Core.ReadStatus.InvalidIndex,");
        writer.Indent++;
        writer.Line("global::FontWeave.Core.DiagnosticCode.IndexOutOfRange,");
        writer.Line($"Location.AtLocal((global::FontWeave.Core.DataField){count.FieldId}, countPosition, ordinal),");
        writer.Line("out diagnostic, ordinal < 0 ? 0UL : (ulong)ordinal, count);");
        writer.Indent -= 2;
        writer.Line("}");
        writer.Line($"status = TryEvaluateArray{array.Name}Start(out ulong start, out diagnostic);");
        writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
        writer.Line($"ulong rowPosition = start + (ulong)ordinal * {U(array.Stride)};");
        writer.Line($"if (!TrySlice(_data, rowPosition, {U(array.Stride)}, out global::System.ReadOnlySpan<byte> row))");
        writer.Indent++;
        writer.Line("return Fail(global::FontWeave.Core.ReadStatus.Truncated,");
        writer.Indent++;
        writer.Line("global::FontWeave.Core.DiagnosticCode.TruncatedData,");
        writer.Line("Location.AtLocal(global::FontWeave.Core.DataField.None, rowPosition, ordinal),");
        writer.Line($"out diagnostic, (ulong)_data.Length, rowPosition + {U(array.Stride)});");
        writer.Indent -= 2;

        EmitRecordFields(writer, array);
        writer.Indent--;
        writer.Line("}");
    }

    private static void EmitRecordFields(CodeWriter writer, ArrayModel array)
    {
        foreach (ScalarModel field in array.Fields)
            writer.Line($"{field.CsType} value{field.Name} = {ReadExpression(field, "row", field.Position.Constant)};");

        var arguments = new StringBuilder("ordinal");
        foreach (ScalarModel field in array.Fields)
            arguments.Append(", value").Append(field.Name);
        writer.Line($"record = new {array.Name}Data({arguments});");
        writer.Line("diagnostic = default;");
        writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
    }

    private static void EmitPayload(CodeWriter writer, TableModel model, PayloadModel payload)
    {
        ArrayModel array = FindArray(model, payload.Array);
        ScalarModel offset = FindArrayField(array, payload.Offset);
        ScalarModel? baseScalar = payload.Base is null ? null : FindScalar(model, payload.Base);

        writer.Line($"public global::FontWeave.Core.ReadStatus TryGet{payload.Array}Payload(int ordinal,");
        writer.Indent++;
        writer.Line("out global::System.ReadOnlySpan<byte> payload, out global::FontWeave.Core.FontDiagnostic diagnostic)");
        writer.Indent--;
        writer.Line("{");
        writer.Indent++;
        writer.Line("payload = default;");
        writer.Line($"global::FontWeave.Core.ReadStatus status = TryGet{payload.Array}(ordinal, out {array.Name}Data record, out diagnostic);");
        writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
        writer.Line($"status = TryGet{payload.Minimum}(out var minimumRaw, out diagnostic);");
        writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
        writer.Line("ulong minimum = (ulong)minimumRaw;");
        writer.Line("if (minimum > (ulong)_data.Length)");
        writer.Indent++;
        writer.Line("return Fail(global::FontWeave.Core.ReadStatus.Truncated,");
        writer.Indent++;
        writer.Line("global::FontWeave.Core.DiagnosticCode.TruncatedData,");
        writer.Line("Location.AtLocal(global::FontWeave.Core.DataField.None, minimum), out diagnostic,");
        writer.Line("(ulong)_data.Length, minimum);");
        writer.Indent -= 2;
        if (baseScalar is not null)
        {
            writer.Line($"status = TryGet{payload.Base}(out var baseRaw, out diagnostic);");
            writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
            writer.Line("ulong storageBase = (ulong)baseRaw;");
            writer.Line($"status = TryEvaluateScalar{baseScalar.Name}Position(out ulong basePosition, out diagnostic);");
            writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
            if (!baseScalar.ZeroAllowed)
            {
                writer.Line("if (storageBase == 0)");
                writer.Indent++;
                writer.Line("return Fail(global::FontWeave.Core.ReadStatus.InvalidOffset,");
                writer.Indent++;
                writer.Line("global::FontWeave.Core.DiagnosticCode.InvalidValue,");
                writer.Line($"Location.AtLocal((global::FontWeave.Core.DataField){baseScalar.FieldId}, basePosition),");
                writer.Line("out diagnostic, 0, 1);");
                writer.Indent -= 2;
            }
            writer.Line("if (storageBase < minimum)");
            writer.Indent++;
            writer.Line("return Fail(global::FontWeave.Core.ReadStatus.InvalidOffset,");
            writer.Indent++;
            writer.Line("global::FontWeave.Core.DiagnosticCode.StorageBeforeRecords,");
            writer.Line($"Location.AtLocal((global::FontWeave.Core.DataField){baseScalar.FieldId}, basePosition), out diagnostic,");
            writer.Line("storageBase, minimum);");
            writer.Indent -= 2;
            writer.Line("if (storageBase > (ulong)_data.Length)");
            writer.Indent++;
            writer.Line("return Fail(global::FontWeave.Core.ReadStatus.InvalidOffset,");
            writer.Indent++;
            writer.Line("global::FontWeave.Core.DiagnosticCode.RangeOutsideSource,");
            writer.Line($"Location.AtLocal((global::FontWeave.Core.DataField){baseScalar.FieldId}, basePosition), out diagnostic,");
            writer.Line("storageBase, (ulong)_data.Length);");
            writer.Indent -= 2;
        }
        writer.Line($"ulong encodedOffset = (ulong)record.{payload.Offset};");

        if (!offset.ZeroAllowed)
        {
            writer.Line("if (encodedOffset == 0)");
            writer.Line("{");
            writer.Indent++;
            writer.Line($"status = TryEvaluateArray{array.Name}Start(out ulong arrayStart, out diagnostic);");
            writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
            writer.Line($"ulong fieldPosition = arrayStart + (ulong)ordinal * {U(array.Stride)} + {U(offset.Position.Constant)};");
            writer.Line("return Fail(global::FontWeave.Core.ReadStatus.InvalidOffset,");
            writer.Indent++;
            writer.Line("global::FontWeave.Core.DiagnosticCode.InvalidValue,");
            writer.Line($"Location.AtLocal((global::FontWeave.Core.DataField){offset.FieldId}, fieldPosition, ordinal),");
            writer.Line("out diagnostic, 0, 1);");
            writer.Indent -= 2;
            writer.Line("}");
        }

        writer.Line($"ulong absoluteOffset = {(baseScalar is null ? "" : "storageBase + ")}encodedOffset * {U(offset.Scale)};");
        if (baseScalar is null)
        {
            writer.Line("if (absoluteOffset < minimum)");
            writer.Line("{");
            writer.Indent++;
            writer.Line($"status = TryEvaluateArray{array.Name}Start(out ulong arrayStart, out diagnostic);");
            writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
            writer.Line($"ulong fieldPosition = arrayStart + (ulong)ordinal * {U(array.Stride)} + {U(offset.Position.Constant)};");
            writer.Line("return Fail(global::FontWeave.Core.ReadStatus.InvalidOffset,");
            writer.Indent++;
            writer.Line("global::FontWeave.Core.DiagnosticCode.StorageBeforeRecords,");
            writer.Line($"Location.AtLocal((global::FontWeave.Core.DataField){offset.FieldId}, fieldPosition, ordinal),");
            writer.Line("out diagnostic, absoluteOffset, minimum);");
            writer.Indent -= 2;
            writer.Line("}");
        }
        writer.Line($"ulong payloadLength = (ulong)record.{payload.Length};");
        writer.Line("if (!TrySlice(_data, absoluteOffset, payloadLength, out payload))");
        writer.Indent++;
        writer.Line("return Fail(global::FontWeave.Core.ReadStatus.InvalidOffset,");
        writer.Indent++;
        writer.Line("global::FontWeave.Core.DiagnosticCode.RangeOutsideSource,");
        writer.Line("Location.AtLocal(global::FontWeave.Core.DataField.Payload, absoluteOffset, ordinal),");
        writer.Line("out diagnostic, absoluteOffset + payloadLength, (ulong)_data.Length);");
        writer.Indent -= 2;
        writer.Line("diagnostic = default;");
        writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
        writer.Indent--;
        writer.Line("}");
    }

    private static void EmitKnownVersion(CodeWriter writer, TableModel model)
    {
        writer.Line("private global::FontWeave.Core.ReadStatus TryRequireKnownVersion(out ulong version,");
        writer.Indent++;
        writer.Line("out global::FontWeave.Core.FontDiagnostic diagnostic)");
        writer.Indent--;
        writer.Line("{");
        writer.Indent++;
        writer.Line("version = default;");
        if (model.VersionField is null)
        {
            writer.Line("diagnostic = default;");
            writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
        }
        else
        {
            ScalarModel version = FindScalar(model, model.VersionField);
            writer.Line($"global::FontWeave.Core.ReadStatus status = TryGet{version.Name}(out {version.CsType} rawVersion, out diagnostic);");
            writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
            writer.Line("version = (ulong)rawVersion;");
            if (model.SupportedVersions.Length != 0)
            {
                var condition = new StringBuilder();
                for (int i = 0; i < model.SupportedVersions.Length; i++)
                {
                    if (i != 0) condition.Append(" || ");
                    condition.Append("version == ").Append(U(model.SupportedVersions[i]));
                }
                writer.Line($"if ({condition})");
                writer.Line("{");
                writer.Indent++;
                writer.Line("diagnostic = default;");
                writer.Line("return global::FontWeave.Core.ReadStatus.Done;");
                writer.Indent--;
                writer.Line("}");
            }
            writer.Line($"status = TryEvaluateScalar{version.Name}Position(out ulong versionPosition, out diagnostic);");
            writer.Line("if (status != global::FontWeave.Core.ReadStatus.Done) return status;");
            writer.Line("return Fail(global::FontWeave.Core.ReadStatus.UnsupportedFormat,");
            writer.Indent++;
            writer.Line("global::FontWeave.Core.DiagnosticCode.UnsupportedVersion,");
            writer.Line($"Location.AtLocal((global::FontWeave.Core.DataField){version.FieldId}, versionPosition),");
            writer.Line("out diagnostic, version);");
            writer.Indent--;
        }
        writer.Indent--;
        writer.Line("}");
    }

    private static void EmitRuntimeHelpers(CodeWriter writer, TableModel model)
    {
        writer.Line("private global::FontWeave.Core.DataLocation Location => NormalizeLocation(_location);");
        writer.Line();
        writer.Line("private static global::FontWeave.Core.DataLocation NormalizeLocation(global::FontWeave.Core.DataLocation location) =>");
        writer.Indent++;
        writer.Line($"location == default ? global::FontWeave.Core.DataLocation.Anonymous(0x{model.Tag:X8}u) : location;");
        writer.Indent--;
        writer.Line();
        writer.Line("private static bool TrySlice(global::System.ReadOnlySpan<byte> bytes, ulong offset, ulong length,");
        writer.Indent++;
        writer.Line("out global::System.ReadOnlySpan<byte> value)");
        writer.Indent--;
        writer.Line("{");
        writer.Indent++;
        writer.Line("value = default;");
        writer.Line("if (offset > (ulong)bytes.Length || length > (ulong)bytes.Length - offset) return false;");
        writer.Line("value = bytes.Slice((int)offset, (int)length);");
        writer.Line("return true;");
        writer.Indent--;
        writer.Line("}");
        writer.Line();
        writer.Line("private static global::FontWeave.Core.ReadStatus Fail(global::FontWeave.Core.ReadStatus status,");
        writer.Indent++;
        writer.Line("global::FontWeave.Core.DiagnosticCode code, global::FontWeave.Core.DataLocation location,");
        writer.Line("out global::FontWeave.Core.FontDiagnostic diagnostic, ulong detail = 0, ulong expected = 0)");
        writer.Indent--;
        writer.Line("{");
        writer.Indent++;
        writer.Line("diagnostic = new global::FontWeave.Core.FontDiagnostic(code, location, detail, expected);");
        writer.Line("return status;");
        writer.Indent--;
        writer.Line("}");
    }

    private static void EmitPosition(CodeWriter writer, PositionModel position, string target)
    {
        writer.Line($"{target} = default;");
        writer.Line($"ulong computedPosition = {U(position.Constant)};");
        if (position.Base is not null)
        {
            writer.Line($"global::FontWeave.Core.ReadStatus baseStatus = TryGet{position.Base}(out var baseValue, out diagnostic);");
            writer.Line("if (baseStatus != global::FontWeave.Core.ReadStatus.Done) return baseStatus;");
            writer.Line("computedPosition += (ulong)baseValue;");
        }
        if (position.Count is not null)
        {
            writer.Line($"global::FontWeave.Core.ReadStatus countStatus = TryGet{position.Count}(out var countValue, out diagnostic);");
            writer.Line("if (countStatus != global::FontWeave.Core.ReadStatus.Done) return countStatus;");
            writer.Line($"computedPosition += (ulong)countValue * {U(position.Stride)};");
        }
        writer.Line($"{target} = computedPosition;");
    }

    private static string ReadExpression(ScalarModel scalar, string bytes, ulong offset)
    {
        if (scalar.Type is WireType.UInt8 or WireType.Int8)
        {
            string value = $"{bytes}[{offset.ToString(CultureInfo.InvariantCulture)}]";
            return scalar.Type == WireType.Int8 ? $"unchecked((sbyte){value})" : value;
        }
        string suffix = scalar.Endian == WireEndian.Big ? "BigEndian" : "LittleEndian";
        string method = scalar.Type switch
        {
            WireType.UInt16 => "ReadUInt16",
            WireType.UInt32 => "ReadUInt32",
            WireType.Int16 => "ReadInt16",
            WireType.Int64 => "ReadInt64",
            _ => "ReadInt32",
        };
        string source = offset == 0 ? bytes : $"{bytes}.Slice({offset.ToString(CultureInfo.InvariantCulture)})";
        return $"global::System.Buffers.Binary.BinaryPrimitives.{method}{suffix}({source})";
    }

    private static ScalarModel FindScalar(TableModel model, string name)
    {
        foreach (ScalarModel scalar in model.Scalars)
            if (scalar.Name == name) return scalar;
        throw new InvalidOperationException($"Scalar '{name}' was not found in '{model.Name}'.");
    }

    private static ArrayModel FindArray(TableModel model, string name)
    {
        foreach (ArrayModel array in model.Arrays)
            if (array.Name == name) return array;
        throw new InvalidOperationException($"Array '{name}' was not found in '{model.Name}'.");
    }

    private static ScalarModel FindArrayField(ArrayModel array, string name)
    {
        foreach (ScalarModel field in array.Fields)
            if (field.Name == name) return field;
        throw new InvalidOperationException($"Field '{name}' was not found in array '{array.Name}'.");
    }

    private static string U(ulong value) => value.ToString(CultureInfo.InvariantCulture) + "UL";
    private static string U(int value) => ((ulong)value).ToString(CultureInfo.InvariantCulture) + "UL";

    private sealed class CodeWriter
    {
        private readonly StringBuilder _builder = new();
        public int Indent { get; set; }

        public void Line(string text = "")
        {
            if (text.Length != 0) _builder.Append(' ', Indent * 4).Append(text);
            _builder.Append('\n');
        }

        public override string ToString() => _builder.ToString();
    }
}
